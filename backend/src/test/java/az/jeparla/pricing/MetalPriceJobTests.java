    @Test
    void oneBadVariantDoesNotStopTheOthers() {
        STUB.always(Answer.fixture("cbar-2026-11-06.xml"));
        long first = db.metalLinkedVariant(Metal.GOLD, 585, "1.000", "100.00", "0", "0", "0", "0", null, null);
        long usd = db.metalLinkedVariant(Metal.GOLD, 585, "1.000", "100.00", "0", "0", "0", "0", null, null);
        long dbFailure = db.metalLinkedVariant(Metal.GOLD, 585, "1.000", "100.00", "0", "0", "0", "0", null, null);
        long last = db.metalLinkedVariant(Metal.GOLD, 585, "1.000", "100.00", "0", "0", "0", "0", null, null);
        // A price in another currency cannot come from an AZN quote.
        db.jdbc().update("UPDATE product_variants SET currency = 'USD' WHERE id = ?", usd);
        // A database error on one row (batch size is 2: it shares a batch with "last").
        db.jdbc().execute("""
                CREATE FUNCTION test_fail_variant() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN
                    IF NEW.id = %d AND NEW.price <> OLD.price THEN RAISE EXCEPTION 'test failure'; END IF;
                    RETURN NEW;
                END $$""".formatted(dbFailure));
        db.jdbc().execute("""
                CREATE TRIGGER test_fail_variant BEFORE UPDATE ON product_variants
                FOR EACH ROW EXECUTE FUNCTION test_fail_variant()""");
        try {
            Report report = job.runLocked(Trigger.INTERNAL).orElseThrow();

            assertThat(report.repriced().get(Metal.GOLD)).isEqualTo(new RepricingService.Result(2, 0, 0, 2));
        } finally {
            db.jdbc().execute("DROP TRIGGER test_fail_variant ON product_variants");
            db.jdbc().execute("DROP FUNCTION test_fail_variant()");
        }
        // 1 x 585/1000 x 221.1147 = 129.35
        assertThat(db.price(first)).isEqualTo(new BigDecimal("129.35"));
        assertThat(db.price(last)).isEqualTo(new BigDecimal("129.35"));
        for (long failed : List.of(usd, dbFailure)) {
            assertThat(db.price(failed)).isEqualTo(new BigDecimal("100.00"));
            assertThat(db.snapshotOf(failed)).isNull();
            assertThat(db.historyRows(failed)).isZero();
        }
        // The next run tries the failed ones again; the others are done.
        Report again = job.runLocked(Trigger.INTERNAL).orElseThrow();
        assertThat(again.repriced().get(Metal.GOLD)).isEqualTo(new RepricingService.Result(1, 0, 2, 1));
        assertThat(db.price(dbFailure)).isEqualTo(new BigDecimal("129.35"));
    }

    @Test
    void runIsSkippedWhileAnotherHoldsTheLock() {
        STUB.always(Answer.fixture("cbar-2026-11-06.xml"));
        Optional<SimpleLock> other = locks.lock(new LockConfiguration(Instant.now(), MetalPriceJob.LOCK_NAME,
                Duration.ofMinutes(5), Duration.ZERO));
        assertThat(other).isPresent();
        try {
            assertThat(job.runLocked(Trigger.SCHEDULE)).isEmpty();
            assertThat(job.repriceLocked(Trigger.ADMIN)).isEmpty();
            assertThat(STUB.requests()).isEmpty();
            assertThat(db.count("SELECT count(*) FROM metal_price_snapshots")).isZero();
        } finally {
            other.get().unlock();
        }
        assertThat(job.runLocked(Trigger.INTERNAL)).isPresent();
    }

    @Test
    void twoConcurrentRunsExecuteOnce() throws Exception {
        CountDownLatch release = new CountDownLatch(1);
        STUB.always(Answer.fixture("cbar-2026-11-06.xml").heldBy(release));
        long gold = db.metalLinkedVariant(Metal.GOLD, 585, "1.000", "100.00", "0", "0", "0", "0", null, null);

        CompletableFuture<Optional<Report>> first = CompletableFuture.supplyAsync(
                () -> job.runLocked(Trigger.SCHEDULE));
        // Wait until the first run is inside the lock (its CBAR request is in flight).
        long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(20);
        while (STUB.requests().isEmpty() && System.nanoTime() < deadline) {
            Thread.onSpinWait();
        }
        assertThat(STUB.requests()).hasSize(1);
        CompletableFuture<Optional<Report>> second = CompletableFuture.supplyAsync(
                () -> job.runLocked(Trigger.SCHEDULE));

        assertThat(second.get(20, TimeUnit.SECONDS)).isEmpty();
        release.countDown();
        assertThat(first.get(20, TimeUnit.SECONDS)).isPresent();

        assertThat(STUB.requests()).hasSize(1);
        assertThat(db.count("SELECT count(*) FROM metal_price_snapshots")).isEqualTo(4);
        assertThat(db.historyRows(gold)).isEqualTo(1);
        // A scheduled run keeps the lock for lock-at-least-for (1 minute): a second instance firing the same
        // cron a moment later is skipped too.
        assertThat(job.runLocked(Trigger.SCHEDULE)).isEmpty();
    }
