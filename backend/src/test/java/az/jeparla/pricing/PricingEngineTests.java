package az.jeparla.pricing;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import az.jeparla.pricing.PricingEngine.Breakdown;
import az.jeparla.pricing.PricingEngine.Clamp;
import az.jeparla.pricing.PricingEngine.Rule;
import java.math.BigDecimal;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

/**
 * The shared examples of frontend/src/lib/pricing.test.ts and the edge cases of PLAN 5.10 (rounding,
 * limits). The full parity table generated by pricing.ts is {@link PricingEngineParityTests}.
 */
class PricingEngineTests {

    private static BigDecimal d(String value) {
        return value == null ? null : new BigDecimal(value);
    }

    private static Rule rule(String laborPerGram, String laborFixed, String stone, String markup, String min,
            String max) {
        return new Rule(d(laborPerGram), d(laborFixed), d(stone), d(markup), d(min), d(max));
    }

    private static String price(String weight, int fineness, String gram, Rule rule) {
        return PricingEngine.price(d(weight), fineness, d(gram), rule).toPlainString();
    }

    @Test
    void gramPriceDividesTheTroyOunce() {
        assertThat(PricingEngine.gramPrice(d("3110.34768"))).isEqualByComparingTo("100.0000").hasToString("100.0000");
        assertThat(PricingEngine.gramPrice(d("7000.00"))).hasToString("225.0552");
        // The CBAR bulletin of 06.11.2026 (src/test/resources/cbar).
        assertThat(PricingEngine.gramPrice(d("6877.435"))).hasToString("221.1147");
        assertThat(PricingEngine.gramPrice(d("87.6642"))).hasToString("2.8185");
    }

    @Test
    void sharedExamplesOfTheFrontend() {
        assertThat(price("3", 585, "200", Rule.metalOnly())).isEqualTo("351.00");
        assertThat(price("3.250", 750, "225.0547", rule("12", "20", "400", "15", null, null))).isEqualTo("1158.71");
        assertThat(price("1", 585, "200", rule("0", "0", "0", "0", "150.00", null))).isEqualTo("150.00");
        assertThat(price("1", 585, "200", rule("0", "0", "0", "0", null, "100.00"))).isEqualTo("100.00");
        assertThat(price("0.1", 999, "0.15", Rule.metalOnly())).isEqualTo("0.01");
        assertThat(price("1", 1000, "0.125", rule("0", "0.2", "0", "0", null, null))).isEqualTo("0.33");
    }

    @Test
    void breakdownShowsThePartsBehindTheTotal() {
        Breakdown b = PricingEngine.breakdown(d("3.250"), 750, d("225.0547"), rule("12", "20", "400", "15", null, null));
        assertThat(b.metal()).hasToString("548.57");
        assertThat(b.labor()).hasToString("59.00");
        assertThat(b.stone()).hasToString("400.00");
        assertThat(b.markup()).hasToString("151.14");
        assertThat(b.clamped()).isNull();
        assertThat(b.total()).hasToString("1158.71");
    }

    @ParameterizedTest(name = "{0} g x {1} x {2} = {3}")
    @CsvSource({
            // Exactly half a cent rounds up (away from zero), as big.js roundHalfUp.
            "1, 1000, 0.125, 0.13",
            "1, 1000, 1.005, 1.01",
            "1, 1000, 2.675, 2.68",
            "1, 1000, 0.015, 0.02",
            // Just below half a cent rounds down.
            "1, 1000, 1.0049999, 1.00",
            "1, 1000, 0.0149, 0.01",
            // Half a cent built from weight x fineness.
            "0.005, 1000, 1, 0.01",
            "0.001, 500, 9, 0.00",
            "0.001, 500, 10, 0.01",
    })
    void roundsHalfUpToCents(String weight, int fineness, String gram, String expected) {
        assertThat(price(weight, fineness, gram, Rule.metalOnly())).isEqualTo(expected);
    }

    @Test
    void givesTheExactDecimalResult() {
        // In binary floating point 1.005 is 1.00499999999999989..., which would round to 1.00, and
        // 0.1 x 0.2 + 0.1 is 0.12000000000000001.
        assertThat(price("1", 1000, "1.005", Rule.metalOnly())).isEqualTo("1.01");
        assertThat(price("0.1", 1000, "0.2", rule("0", "0.1", "0", "0", null, null))).isEqualTo("0.12");
    }

    @Test
    void appliesTheMinimumThenTheMaximum() {
        Rule both = rule("0", "0", "0", "0", "100.00", "200.00");
        assertThat(PricingEngine.breakdown(d("1"), 1000, d("50"), both).clamped()).isEqualTo(Clamp.MIN);
        assertThat(price("1", 1000, "50", both)).isEqualTo("100.00");
        assertThat(PricingEngine.breakdown(d("1"), 1000, d("500"), both).clamped()).isEqualTo(Clamp.MAX);
        assertThat(price("1", 1000, "500", both)).isEqualTo("200.00");
        assertThat(PricingEngine.breakdown(d("1"), 1000, d("150"), both).clamped()).isNull();
        // On the limit is not clamped.
        assertThat(PricingEngine.breakdown(d("1"), 1000, d("100"), both).clamped()).isNull();
        assertThat(PricingEngine.breakdown(d("1"), 1000, d("200"), both).clamped()).isNull();
        // The limits are compared with the unrounded price: 99.996 is below 100.00 although it rounds to 100.00.
        assertThat(PricingEngine.breakdown(d("1"), 1000, d("99.996"), both).clamped()).isEqualTo(Clamp.MIN);
        // Equal limits fix the price.
        Rule fixed = rule("0", "0", "0", "0", "300.00", "300.00");
        assertThat(price("1", 1000, "500", fixed)).isEqualTo("300.00");
        assertThat(price("1", 1000, "5", fixed)).isEqualTo("300.00");
    }

    @Test
    void percentChangeLikeTheAdminPanel() {
        assertThat(PricingEngine.percentChange(d("100"), d("101.25"))).hasToString("1.3");
        assertThat(PricingEngine.percentChange(d("200"), d("197"))).hasToString("-1.5");
        assertThat(PricingEngine.percentChange(d("0"), d("5"))).hasToString("0.0");
        assertThat(PricingEngine.percentChange(d("100"), d("110.04"))).hasToString("10.0");
        assertThat(PricingEngine.percentChange(d("100"), d("110.05"))).hasToString("10.1");
    }

    @Test
    void refusesInputsOutsideTheSchema() {
        assertThatThrownBy(() -> price("0", 585, "200", Rule.metalOnly())).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> price("1", 0, "200", Rule.metalOnly())).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> price("1", 1001, "200", Rule.metalOnly())).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> price("1", 585, "0", Rule.metalOnly())).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> price("1", 585, "-1", Rule.metalOnly())).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> rule("-1", "0", "0", "0", null, null)).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> rule("0", "0", "0", "0", "200.00", "100.00"))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> PricingEngine.gramPrice(d("0"))).isInstanceOf(IllegalArgumentException.class);
        // NUMERIC(12,2) holds at most 9 999 999 999.99.
        assertThatThrownBy(() -> price("99999.999", 1000, "999999", Rule.metalOnly()))
                .isInstanceOf(ArithmeticException.class);
    }
}
