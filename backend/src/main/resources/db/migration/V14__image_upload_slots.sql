-- Presigned photo uploads (#154). Every presign the API hands out is a row: an issued, not attached,
-- not expired upload counts toward the 8 photos of its product, every upload of the last 24 hours
-- toward the daily limit of its store, and the cleanup job deletes the staged file of an upload that
-- was never attached. Rows are purged two days after they were issued.
CREATE TABLE image_upload_slots
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Public key the file gets when attached; until then it waits under staging/<key> in the private bucket.
    storage_key  TEXT        NOT NULL UNIQUE,
    product_id   BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    store_id     BIGINT      NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL,
    -- End of the presigned URL; the file can be attached a little later (MerchantImageService).
    expires_at   TIMESTAMPTZ NOT NULL,
    attached_at  TIMESTAMPTZ,
    -- The staged file was deleted (cleanup job).
    discarded_at TIMESTAMPTZ,
    CONSTRAINT image_upload_slots_expiry CHECK (expires_at > created_at),
    CONSTRAINT image_upload_slots_one_end CHECK (attached_at IS NULL OR discarded_at IS NULL)
);

-- Open uploads of a product, and the cleanup's search for stale ones.
CREATE INDEX image_upload_slots_open_idx ON image_upload_slots (product_id, expires_at)
    WHERE attached_at IS NULL AND discarded_at IS NULL;
CREATE INDEX image_upload_slots_stale_idx ON image_upload_slots (expires_at)
    WHERE attached_at IS NULL AND discarded_at IS NULL;
-- Daily limit of a store, and the purge.
CREATE INDEX image_upload_slots_store_idx ON image_upload_slots (store_id, created_at);
CREATE INDEX image_upload_slots_created_idx ON image_upload_slots (created_at);
