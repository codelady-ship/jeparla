-- Refresh tokens (#34). Only the SHA-256 hash of a token is stored, never the token itself.
-- Every login starts a family; each refresh marks the presented token used and issues the next
-- one in the same family. A used or revoked token presented again means it leaked: the whole
-- family is revoked (reuse detection). Rows stay until they expire, so reuse is still detected.

CREATE TABLE refresh_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id  UUID        NOT NULL,
    -- Lowercase hex SHA-256 of the token.
    token_hash TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    -- Set when the token was exchanged for the next one.
    used_at    TIMESTAMPTZ,
    -- Set on logout, on reuse detection and when an account is blocked.
    revoked_at TIMESTAMPTZ,
    CONSTRAINT refresh_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT refresh_tokens_token_hash_format CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT refresh_tokens_expiry CHECK (expires_at > created_at)
);

CREATE INDEX refresh_tokens_family_id_idx ON refresh_tokens (family_id);
CREATE INDEX refresh_tokens_user_id_idx ON refresh_tokens (user_id);
-- Cleanup of expired rows.
CREATE INDEX refresh_tokens_expires_at_idx ON refresh_tokens (expires_at);
