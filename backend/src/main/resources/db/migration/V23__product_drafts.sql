-- Product drafts from photos and catalog PDFs (#129, #109).
--
-- A draft is one photo in the private bucket (a phone camera shot, one of many photos picked at once, or an image
-- taken out of a catalog PDF) with what the PDF page suggested: a name, a price, a weight. The seller turns it into
-- a product (the normal form, always a DRAFT product) or deletes it; nothing is published from here. Money and
-- weight are NUMERIC, like everywhere.

CREATE TABLE product_drafts
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id         BIGINT        NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    source           VARCHAR(16)   NOT NULL,
    -- Private bucket key: drafts/<store id>/<uuid>.<ext>; never public.
    image_key        VARCHAR(255)  NOT NULL UNIQUE,
    content_type     VARCHAR(32)   NOT NULL,
    width            INTEGER       NOT NULL,
    height           INTEGER       NOT NULL,
    -- Page of the PDF the image came from (1-based); null for photos.
    pdf_page         INTEGER,
    suggested_name   VARCHAR(120),
    suggested_price  NUMERIC(12, 2),
    suggested_weight NUMERIC(8, 3),
    created_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT product_drafts_source CHECK (source IN ('PHOTO', 'CAMERA', 'PDF')),
    CONSTRAINT product_drafts_content_type CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT product_drafts_size CHECK (width > 0 AND height > 0),
    CONSTRAINT product_drafts_page CHECK ((source = 'PDF') = (pdf_page IS NOT NULL) AND (pdf_page IS NULL OR pdf_page > 0)),
    CONSTRAINT product_drafts_price CHECK (suggested_price IS NULL OR suggested_price > 0),
    CONSTRAINT product_drafts_weight CHECK (suggested_weight IS NULL OR suggested_weight > 0)
);

CREATE INDEX product_drafts_store ON product_drafts (store_id, created_at);
