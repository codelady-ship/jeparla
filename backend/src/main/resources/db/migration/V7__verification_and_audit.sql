-- Jeparla Verified documents (PLAN 5.9) and the audit log (PLAN 5.8, 5.13).

-- Files live in the private bucket; only the key is stored. Admins read them through
-- short-lived signed URLs (#40). UUID ids: document ids are not guessable or countable.
CREATE TABLE verification_documents
(
    id           UUID        NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
    -- Documents are evidence: a store or product with documents cannot be removed.
    store_id     BIGINT      NOT NULL REFERENCES stores (id) ON DELETE RESTRICT,
    -- Set for product expertise documents (assay certificate, lab report).
    product_id   BIGINT REFERENCES products (id) ON DELETE RESTRICT,
    -- Which Jeparla Verified check the document supports.
    check_kind   TEXT        NOT NULL,
    kind         TEXT        NOT NULL,
    storage_key  TEXT        NOT NULL,
    file_name    TEXT        NOT NULL,
    content_type TEXT        NOT NULL,
    size_bytes   BIGINT      NOT NULL,
    pages        INTEGER,
    -- Hex SHA-256 of the file, to spot the same file uploaded twice.
    sha256       CHAR(64),
    status       TEXT        NOT NULL DEFAULT 'PENDING',
    review_note  TEXT,
    uploaded_by  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reviewed_by  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT verification_documents_storage_key_key UNIQUE (storage_key),
    CONSTRAINT verification_documents_check_kind CHECK (check_kind IN ('SELLER', 'DOCUMENTS', 'EXPERTISE')),
    CONSTRAINT verification_documents_expertise_product CHECK ((check_kind = 'EXPERTISE') = (product_id IS NOT NULL)),
    CONSTRAINT verification_documents_kind CHECK (
        kind IN ('TAX_ID', 'TRADE_LICENSE', 'ASSAY_CERTIFICATE', 'LAB_REPORT')),
    CONSTRAINT verification_documents_content_type CHECK (
        content_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    -- 10 MB per file, as in the seller sign-up form.
    CONSTRAINT verification_documents_size CHECK (size_bytes > 0 AND size_bytes <= 10485760),
    CONSTRAINT verification_documents_pages CHECK (pages IS NULL OR pages > 0),
    CONSTRAINT verification_documents_sha256 CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT verification_documents_status CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED'))
);

CREATE INDEX verification_documents_store_idx ON verification_documents (store_id, check_kind);
CREATE INDEX verification_documents_product_idx ON verification_documents (product_id);
CREATE INDEX verification_documents_pending_idx ON verification_documents (created_at) WHERE status = 'PENDING';

-- Admin and merchant actions (#34, #40). Append-only by convention; a retention job
-- removes old rows (PLAN 3a, VM disk is limited).
CREATE TABLE audit_logs
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The row stays when the account is deleted; actor_label keeps who it was.
    actor_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_label TEXT        NOT NULL,
    actor_role  TEXT,
    action      TEXT        NOT NULL,
    target_type TEXT        NOT NULL,
    -- BIGINT or UUID of the target, as text.
    target_id   TEXT,
    target_name TEXT,
    reason      TEXT,
    -- Extra structured context. Never passwords, tokens or document contents.
    details     JSONB,
    ip_address  INET,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT audit_logs_actor_role CHECK (actor_role IS NULL OR actor_role IN ('ADMIN', 'MERCHANT', 'USER', 'SYSTEM')),
    CONSTRAINT audit_logs_target_type CHECK (
        target_type IN ('STORE', 'PRODUCT', 'CHECK', 'USER', 'CATALOG', 'PRICE', 'REPORT')),
    CONSTRAINT audit_logs_action_length CHECK (length(action) BETWEEN 1 AND 64)
);

CREATE INDEX audit_logs_created_idx ON audit_logs (created_at DESC);
CREATE INDEX audit_logs_target_idx ON audit_logs (target_type, target_id);
CREATE INDEX audit_logs_actor_idx ON audit_logs (actor_id);
