-- Suspected forged documents: suspending a store needs two people (#138, docs/legal/sellers-liability.md 3.1).
--
-- An admin who rejects a document for AUTHENTICITY opens a PENDING request; a second admin confirms it (the store
-- is BLOCKED and the seller gets the non-accusing notice of section 2d) or dismisses it. The database refuses a
-- decision by the person who asked (four eyes) and a second open request for the same store.

CREATE TABLE store_suspension_requests
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id     BIGINT      NOT NULL REFERENCES stores (id) ON DELETE RESTRICT,
    -- The rejected document that raised the suspicion; it stays as evidence (legal hold, 3.4).
    document_id  UUID REFERENCES verification_documents (id) ON DELETE RESTRICT,
    status       VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    requested_by BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    note         VARCHAR(1000),
    decided_by   BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    decided_at   TIMESTAMPTZ,
    decision_note VARCHAR(1000),
    CONSTRAINT store_suspension_requests_status CHECK (status IN ('PENDING', 'CONFIRMED', 'DISMISSED')),
    CONSTRAINT store_suspension_requests_decided CHECK ((status = 'PENDING') = (decided_at IS NULL)),
    CONSTRAINT store_suspension_requests_four_eyes CHECK (
        decided_by IS NULL OR requested_by IS NULL OR decided_by <> requested_by)
);

CREATE UNIQUE INDEX store_suspension_requests_one_open ON store_suspension_requests (store_id)
    WHERE status = 'PENDING';
CREATE INDEX store_suspension_requests_queue ON store_suspension_requests (status, requested_at);
