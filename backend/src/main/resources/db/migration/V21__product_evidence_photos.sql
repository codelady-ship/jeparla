-- Hallmark and label photos of a product (#106): evidence, not gallery.
--
-- A photo of the assay hallmark (HALLMARK, close-up) and of the shop label with weight and fineness (TAG); at most
-- one of each per product. The seller uploads them like gallery photos (presigned PUT into the private staging
-- area, magic-number check, then copied to the public bucket) and they are shown only with the APPROVED product.
-- An admin compares the photo with the product data and marks it VERIFIED or REJECTED (audited); a new photo
-- starts PENDING again. A hallmark photo is not a laboratory assay (PLAN 5.9), only what the seller showed.
--
-- A separate table, not a kind column on product_images: every gallery query (cover, order, the 8-photo limit,
-- the store preview) keeps meaning "gallery" without a filter that could be forgotten.
-- The runtime role gets its grants from the default privileges of V16.

CREATE TABLE product_evidence_photos
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    kind         TEXT        NOT NULL,
    -- Object key in the public bucket, as product_images.storage_key.
    storage_key  TEXT        NOT NULL,
    width        INTEGER     NOT NULL,
    height       INTEGER     NOT NULL,
    content_type TEXT        NOT NULL,
    size_bytes   BIGINT      NOT NULL,
    -- PENDING until an admin looked at it; VERIFIED matches the product data, REJECTED does not (note says why).
    status       TEXT        NOT NULL DEFAULT 'PENDING',
    check_note   TEXT,
    checked_by   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    checked_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_evidence_photos_storage_key_key UNIQUE (storage_key),
    CONSTRAINT product_evidence_photos_storage_key_fragment CHECK (position('#' IN storage_key) = 0),
    CONSTRAINT product_evidence_photos_kind CHECK (kind IN ('HALLMARK', 'TAG')),
    CONSTRAINT product_evidence_photos_dimensions CHECK (width > 0 AND height > 0),
    CONSTRAINT product_evidence_photos_content_type CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT product_evidence_photos_size CHECK (size_bytes > 0),
    CONSTRAINT product_evidence_photos_status CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT product_evidence_photos_checked CHECK ((status = 'PENDING') = (checked_at IS NULL)),
    CONSTRAINT product_evidence_photos_rejected_note CHECK (status <> 'REJECTED' OR check_note IS NOT NULL)
);

-- One photo of each kind per product (a new one replaces the old one).
CREATE UNIQUE INDEX product_evidence_photos_product_kind_key ON product_evidence_photos (product_id, kind);
-- Admin queue: photos waiting for a check, oldest first.
CREATE INDEX product_evidence_photos_pending_idx ON product_evidence_photos (created_at)
    WHERE status = 'PENDING';
CREATE INDEX product_evidence_photos_checked_by_idx ON product_evidence_photos (checked_by);

-- Presigned uploads say what they are for: a gallery photo or one evidence photo kind. Open evidence uploads
-- do not take the places of the 8 gallery photos.
ALTER TABLE image_upload_slots
    ADD COLUMN kind TEXT NOT NULL DEFAULT 'GALLERY',
    ADD CONSTRAINT image_upload_slots_kind CHECK (kind IN ('GALLERY', 'HALLMARK', 'TAG'));
