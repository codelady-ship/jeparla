-- Daily CBAR metal quotes (PLAN 5.10, #43). CBAR quotes AZN per troy ounce;
-- price_per_gram = price_per_ounce / 31.1034768, rounded to 4 decimals (same as the frontend).

CREATE TABLE metal_price_snapshots
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metal           TEXT           NOT NULL,
    -- Business date of the quote; weekends and holidays keep the last available date.
    quote_date      DATE           NOT NULL,
    price_per_ounce NUMERIC(14, 4) NOT NULL,
    price_per_gram  NUMERIC(14, 4) NOT NULL,
    currency        CHAR(3)        NOT NULL DEFAULT 'AZN',
    -- CBAR, or ADMIN for a manual override.
    source          TEXT           NOT NULL,
    -- HELD: changed more than the sanity limit, waits for an admin. Only APPLIED quotes price products.
    status          TEXT           NOT NULL DEFAULT 'APPLIED',
    -- Percent change against the quote in use, e.g. 12.40.
    change_percent  NUMERIC(7, 2),
    fetched_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    decided_by      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    decided_at      TIMESTAMPTZ,
    note            TEXT,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- The fetch job is idempotent: a second run for the same day inserts nothing.
    CONSTRAINT metal_price_snapshots_metal_date_source_key UNIQUE (metal, quote_date, source),
    CONSTRAINT metal_price_snapshots_metal CHECK (metal IN ('GOLD', 'SILVER', 'PLATINUM', 'PALLADIUM')),
    CONSTRAINT metal_price_snapshots_prices CHECK (price_per_ounce > 0 AND price_per_gram > 0),
    CONSTRAINT metal_price_snapshots_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT metal_price_snapshots_source CHECK (source IN ('CBAR', 'ADMIN')),
    CONSTRAINT metal_price_snapshots_status CHECK (status IN ('APPLIED', 'HELD', 'DISCARDED'))
);

-- "Latest applied price per metal" and the history chart.
CREATE INDEX metal_price_snapshots_applied_idx ON metal_price_snapshots (metal, quote_date DESC)
    WHERE status = 'APPLIED';
