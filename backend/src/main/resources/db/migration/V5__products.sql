-- Products, their images, variants, stones and the price history (PLAN 5.2, 5.9, 5.10).

CREATE TABLE products
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id          BIGINT      NOT NULL REFERENCES stores (id) ON DELETE RESTRICT,
    category_id       BIGINT      NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    slug              TEXT        NOT NULL,
    -- The seller writes the Azerbaijani name; en/ru are optional and fall back to az.
    name_az           TEXT        NOT NULL,
    name_en           TEXT,
    name_ru           TEXT,
    description_az    TEXT,
    description_en    TEXT,
    description_ru    TEXT,
    metal             TEXT        NOT NULL,
    -- DRAFT -> IN_REVIEW -> APPROVED | RETURNED; INACTIVE instead of deleting.
    status            TEXT        NOT NULL DEFAULT 'DRAFT',
    -- Admin note when the product is RETURNED or deactivated.
    review_note       TEXT,
    -- Physical expertise check of this product (PLAN 5.9, "verificationStatus").
    expertise_status  TEXT        NOT NULL DEFAULT 'NONE',
    submitted_at      TIMESTAMPTZ,
    published_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Products are never deleted (trigger below): the seller "deletes" = INACTIVE + deleted_at.
    deleted_at        TIMESTAMPTZ,
    search_text       TEXT GENERATED ALWAYS AS (
        jeparla_fold(name_az || ' ' || coalesce(name_en, '') || ' ' || coalesce(name_ru, ''))) STORED,
    CONSTRAINT products_slug_key UNIQUE (slug),
    -- Target of the composite foreign key from product_variants (SKU unique per store).
    CONSTRAINT products_id_store_id_key UNIQUE (id, store_id),
    CONSTRAINT products_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 160),
    CONSTRAINT products_name_az_length CHECK (length(btrim(name_az)) BETWEEN 3 AND 120),
    CONSTRAINT products_metal CHECK (metal IN ('GOLD', 'SILVER', 'PLATINUM', 'PALLADIUM')),
    CONSTRAINT products_status CHECK (status IN ('DRAFT', 'IN_REVIEW', 'APPROVED', 'RETURNED', 'INACTIVE')),
    CONSTRAINT products_expertise_status CHECK (expertise_status IN ('NONE', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT products_published_when_approved CHECK (status <> 'APPROVED' OR published_at IS NOT NULL),
    CONSTRAINT products_deleted_is_inactive CHECK (deleted_at IS NULL OR status = 'INACTIVE')
);

CREATE TRIGGER products_never_deleted
    BEFORE DELETE
    ON products
    FOR EACH ROW
EXECUTE FUNCTION jeparla_forbid_delete();

-- Merchant cabinet: the store's products by status.
CREATE INDEX products_store_status_idx ON products (store_id, status) WHERE deleted_at IS NULL;
-- Public catalog: only APPROVED, not deleted. Newest first, by category, by metal.
CREATE INDEX products_public_published_idx ON products (published_at DESC)
    WHERE status = 'APPROVED' AND deleted_at IS NULL;
CREATE INDEX products_public_category_idx ON products (category_id, published_at DESC)
    WHERE status = 'APPROVED' AND deleted_at IS NULL;
CREATE INDEX products_public_metal_idx ON products (metal)
    WHERE status = 'APPROVED' AND deleted_at IS NULL;
-- Admin moderation queue.
CREATE INDEX products_status_submitted_idx ON products (status, submitted_at);
-- Typo-tolerant search over the folded az/en/ru names.
CREATE INDEX products_search_text_trgm_idx ON products USING gin (search_text gin_trgm_ops);

CREATE TABLE product_images
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    -- Object key in the public bucket; the URL is built from JEPARLA_S3_PUBLIC_URL.
    storage_key  TEXT        NOT NULL,
    alt_az       TEXT,
    alt_en       TEXT,
    alt_ru       TEXT,
    width        INTEGER     NOT NULL,
    height       INTEGER     NOT NULL,
    content_type TEXT        NOT NULL,
    size_bytes   BIGINT      NOT NULL,
    -- AI-generated or AI-edited images carry a visible label (CLAUDE.md, honesty).
    ai_generated BOOLEAN     NOT NULL DEFAULT FALSE,
    sort_order   INTEGER     NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_images_storage_key_key UNIQUE (storage_key),
    CONSTRAINT product_images_dimensions CHECK (width > 0 AND height > 0),
    CONSTRAINT product_images_content_type CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/avif')),
    CONSTRAINT product_images_size CHECK (size_bytes > 0)
);

CREATE INDEX product_images_product_idx ON product_images (product_id, sort_order);

CREATE TABLE product_variants
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT         NOT NULL,
    -- Copy of products.store_id (kept equal by the composite foreign key) so that
    -- the SKU can be unique per store.
    store_id            BIGINT         NOT NULL,
    sku                 TEXT           NOT NULL,
    fineness_id         BIGINT         NOT NULL REFERENCES finenesses (id) ON DELETE RESTRICT,
    weight_grams        NUMERIC(8, 3)  NOT NULL,
    size                TEXT,
    price               NUMERIC(12, 2) NOT NULL,
    currency            CHAR(3)        NOT NULL DEFAULT 'AZN',
    pricing_mode        TEXT           NOT NULL DEFAULT 'FIXED',
    -- METAL_LINKED inputs (PLAN 5.10); zero for FIXED variants.
    labor_per_gram      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    labor_fixed         NUMERIC(12, 2) NOT NULL DEFAULT 0,
    stone_price         NUMERIC(12, 2) NOT NULL DEFAULT 0,
    markup_percent      NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    min_price           NUMERIC(12, 2),
    max_price           NUMERIC(12, 2),
    stock_status        TEXT           NOT NULL DEFAULT 'IN_STOCK',
    -- "Price last updated" on the product page.
    price_updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- The quote the current METAL_LINKED price was computed from.
    metal_snapshot_id   BIGINT REFERENCES metal_price_snapshots (id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- Removed variants stay for the price history; their SKU can be reused.
    deleted_at          TIMESTAMPTZ,
    CONSTRAINT product_variants_product_fk FOREIGN KEY (product_id, store_id)
        REFERENCES products (id, store_id) ON DELETE CASCADE,
    CONSTRAINT product_variants_sku_format CHECK (length(btrim(sku)) BETWEEN 1 AND 64),
    CONSTRAINT product_variants_weight CHECK (weight_grams > 0),
    CONSTRAINT product_variants_price CHECK (price >= 0),
    CONSTRAINT product_variants_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT product_variants_pricing_mode CHECK (pricing_mode IN ('FIXED', 'METAL_LINKED')),
    CONSTRAINT product_variants_pricing_inputs CHECK (
        labor_per_gram >= 0 AND labor_fixed >= 0 AND stone_price >= 0 AND markup_percent >= 0),
    CONSTRAINT product_variants_price_limits CHECK (
        (min_price IS NULL OR min_price >= 0)
            AND (max_price IS NULL OR max_price >= 0)
            AND (min_price IS NULL OR max_price IS NULL OR min_price <= max_price)),
    CONSTRAINT product_variants_stock_status CHECK (stock_status IN ('IN_STOCK', 'MADE_TO_ORDER', 'OUT_OF_STOCK'))
);

-- SKU is unique within a store among live variants.
CREATE UNIQUE INDEX product_variants_store_sku_key ON product_variants (store_id, sku) WHERE deleted_at IS NULL;
CREATE INDEX product_variants_product_idx ON product_variants (product_id) WHERE deleted_at IS NULL;
-- Catalog filters: fineness, price range, weight range.
CREATE INDEX product_variants_fineness_idx ON product_variants (fineness_id) WHERE deleted_at IS NULL;
CREATE INDEX product_variants_price_idx ON product_variants (currency, price) WHERE deleted_at IS NULL;
CREATE INDEX product_variants_weight_idx ON product_variants (weight_grams) WHERE deleted_at IS NULL;
-- Daily repricing job reads only METAL_LINKED variants.
CREATE INDEX product_variants_metal_linked_idx ON product_variants (fineness_id)
    WHERE pricing_mode = 'METAL_LINKED' AND deleted_at IS NULL;
CREATE INDEX product_variants_metal_snapshot_idx ON product_variants (metal_snapshot_id);

CREATE TABLE product_stones
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    stone_type         TEXT        NOT NULL,
    origin             TEXT        NOT NULL DEFAULT 'NATURAL',
    shape              TEXT,
    -- Carat weight of one stone; the row describes `stone_count` identical stones.
    carat              NUMERIC(8, 3),
    stone_count        INTEGER     NOT NULL DEFAULT 1,
    color              TEXT,
    clarity            TEXT,
    cut                TEXT,
    certificate_lab    TEXT,
    certificate_number TEXT,
    sort_order         INTEGER     NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_stones_type CHECK (
        stone_type IN ('DIAMOND', 'RUBY', 'SAPPHIRE', 'EMERALD', 'PEARL', 'CUBIC_ZIRCONIA')),
    CONSTRAINT product_stones_origin CHECK (origin IN ('NATURAL', 'LAB_GROWN')),
    CONSTRAINT product_stones_carat CHECK (carat IS NULL OR carat >= 0),
    CONSTRAINT product_stones_count CHECK (stone_count > 0),
    CONSTRAINT product_stones_certificate CHECK (certificate_number IS NULL OR certificate_lab IS NOT NULL)
);

CREATE INDEX product_stones_product_idx ON product_stones (product_id);
-- Diamond filters: type, carat, shape, color, clarity.
CREATE INDEX product_stones_filter_idx ON product_stones (stone_type, carat);

-- Every price a variant had, with the reason (PLAN 5.10). A wrong price is an S1 bug,
-- so history rows keep their variant and quote (RESTRICT).
CREATE TABLE price_history
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id        BIGINT         NOT NULL REFERENCES product_variants (id) ON DELETE RESTRICT,
    price             NUMERIC(12, 2) NOT NULL,
    previous_price    NUMERIC(12, 2),
    currency          CHAR(3)        NOT NULL,
    -- MERCHANT: edited by the seller; METAL_PRICE: repriced from a new quote; ADMIN: set by an admin.
    reason            TEXT           NOT NULL,
    metal_snapshot_id BIGINT REFERENCES metal_price_snapshots (id) ON DELETE RESTRICT,
    changed_by        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT price_history_price CHECK (price >= 0 AND (previous_price IS NULL OR previous_price >= 0)),
    CONSTRAINT price_history_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT price_history_reason CHECK (reason IN ('MERCHANT', 'METAL_PRICE', 'ADMIN')),
    CONSTRAINT price_history_metal_reason CHECK (reason <> 'METAL_PRICE' OR metal_snapshot_id IS NOT NULL)
);

CREATE INDEX price_history_variant_idx ON price_history (variant_id, created_at DESC);
-- Repricing twice from the same quote writes one row (the job is idempotent, #44).
CREATE UNIQUE INDEX price_history_variant_snapshot_key ON price_history (variant_id, metal_snapshot_id)
    WHERE reason = 'METAL_PRICE';
CREATE INDEX price_history_snapshot_idx ON price_history (metal_snapshot_id);
