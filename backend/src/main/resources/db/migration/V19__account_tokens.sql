-- Email verification and password reset (#131).
--
-- 1. account_tokens: one-time tokens sent by email (or, for a phone-only seller, handed over by an admin).
--    Only the SHA-256 hash is stored, never the token. A token works once (used_at) and only until expires_at:
--    24 hours for an email verification, 1 hour for a password reset.
-- 2. email_outbox.expires_at: the email carries a one-time link. Its body is replaced by a placeholder once it is
--    sent or the link has expired, so the outbox does not keep a working link longer than needed.

CREATE TABLE account_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose    TEXT        NOT NULL,
    -- Lowercase hex SHA-256 of the token.
    token_hash TEXT        NOT NULL,
    -- The address the link was sent to: the token is refused once the account has another email. NULL for a
    -- reset link an admin issued for an account without an email address.
    email      TEXT,
    -- The admin who issued a reset link for a phone-only seller (#52 pending); NULL for self-service tokens.
    issued_by  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    CONSTRAINT account_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT account_tokens_token_hash_format CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT account_tokens_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    CONSTRAINT account_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT account_tokens_verification_email CHECK (purpose <> 'EMAIL_VERIFICATION' OR email IS NOT NULL)
);

CREATE INDEX account_tokens_user_idx ON account_tokens (user_id, purpose) WHERE used_at IS NULL;
-- Cleanup of expired rows.
CREATE INDEX account_tokens_expires_at_idx ON account_tokens (expires_at);

ALTER TABLE email_outbox
    ADD COLUMN expires_at TIMESTAMPTZ;

CREATE INDEX email_outbox_expiring_idx ON email_outbox (expires_at) WHERE expires_at IS NOT NULL;
