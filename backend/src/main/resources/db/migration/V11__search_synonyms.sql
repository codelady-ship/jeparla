-- Search (#38, PLAN 5.3): synonyms the admin manages (PLAN 5.8), used by GET /api/v1/search and
-- /search/suggest. A query word equal to one side of a row also matches the other side, in both
-- directions: "serqa" finds "sırğa", "кольцо" finds "üzük" (useful when a store wrote only the
-- Azerbaijani name). Both sides are single words; matching uses the folded forms (jeparla_fold).
CREATE TABLE search_synonyms
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term           TEXT        NOT NULL,
    synonym        TEXT        NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    term_folded    TEXT GENERATED ALWAYS AS (jeparla_fold(term)) STORED,
    synonym_folded TEXT GENERATED ALWAYS AS (jeparla_fold(synonym)) STORED,
    CONSTRAINT search_synonyms_term_word CHECK (jeparla_fold(term) ~ '^[^ ]{2,40}$'),
    CONSTRAINT search_synonyms_synonym_word CHECK (jeparla_fold(synonym) ~ '^[^ ]{2,40}$'),
    CONSTRAINT search_synonyms_not_same CHECK (jeparla_fold(term) <> jeparla_fold(synonym)),
    CONSTRAINT search_synonyms_pair_key UNIQUE (term_folded, synonym_folded)
);

CREATE INDEX search_synonyms_synonym_folded_idx ON search_synonyms (synonym_folded);

