-- Saved products of signed-in buyers (PLAN 5.11) and buyer complaints (PLAN 5.8).

CREATE TABLE favorites
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deleting an account removes its saved list.
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT favorites_user_product_key UNIQUE (user_id, product_id)
);

CREATE INDEX favorites_product_idx ON favorites (product_id);

CREATE TABLE product_reports
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT      NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    -- Guests can report too; the report outlives the reporter's account.
    reporter_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reason           TEXT        NOT NULL,
    message          TEXT        NOT NULL DEFAULT '',
    status           TEXT        NOT NULL DEFAULT 'OPEN',
    resolution_note  TEXT,
    resolved_by      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    resolved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_reports_reason CHECK (reason IN ('WRONG_PRICE', 'WRONG_INFO', 'FAKE', 'OFFENSIVE', 'OTHER')),
    CONSTRAINT product_reports_message_length CHECK (length(message) <= 2000),
    CONSTRAINT product_reports_status CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED'))
);

CREATE INDEX product_reports_status_idx ON product_reports (status, created_at DESC);
CREATE INDEX product_reports_product_idx ON product_reports (product_id);
