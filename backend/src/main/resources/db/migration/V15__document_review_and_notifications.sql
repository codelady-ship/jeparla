-- Verification documents of precious-metal sellers, their review, the seller's declaration and the
-- notifications that tell the seller about a decision (#40, #138).
--
-- 1. seller_declarations: evidence that the seller confirmed, before an upload, that the documents are genuine
--    and that false or forged documents may lead to liability, including criminal liability
--    (docs/legal/sellers-liability.md, draft until the lawyer approves it, #57). The exact text shown, its
--    version and language, the user and the IP are kept. Append-only (trigger below).
-- 2. document_upload_slots: presigned uploads of documents into the private bucket (as image_upload_slots,
--    V14). The file waits under staging/<key> until its check and then moves to <key> in the same private
--    bucket; documents are never in the public bucket.
-- 3. verification_documents: the review outcome (CHANGES_REQUESTED, a reason category) and the declaration
--    the upload was made under.
-- 4. notifications (in-app) and email_outbox (sent by a job through an EmailSender; #131 picks the provider).
-- 5. audit_logs: documents are a target of their own.

-- ------------------------------------------------------------------ declarations

CREATE TABLE seller_declarations
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL after the account is deleted; user_label keeps who it was.
    user_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    user_label   TEXT        NOT NULL,
    -- Evidence of a store is kept as long as the store (stores are never deleted while they have documents).
    store_id     BIGINT      NOT NULL REFERENCES stores (id) ON DELETE RESTRICT,
    -- Version of the text, e.g. precious-2026-11-10-draft; a new wording gets a new version.
    text_version TEXT        NOT NULL,
    language     TEXT        NOT NULL,
    -- The text exactly as it was shown and confirmed.
    text         TEXT        NOT NULL,
    ip_address   INET,
    confirmed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT seller_declarations_language CHECK (language IN ('az', 'en', 'ru')),
    CONSTRAINT seller_declarations_version CHECK (length(text_version) BETWEEN 1 AND 64),
    CONSTRAINT seller_declarations_text CHECK (length(text) BETWEEN 1 AND 4000)
);

CREATE INDEX seller_declarations_store_idx ON seller_declarations (store_id, confirmed_at DESC);
CREATE INDEX seller_declarations_user_idx ON seller_declarations (user_id);

-- Evidence is never changed or removed. The only change allowed is the user_id that ON DELETE SET NULL clears
-- when an account is deleted (user_label stays).
CREATE FUNCTION jeparla_declarations_append_only() RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.user_id IS NULL
        AND (NEW.id, NEW.user_label, NEW.store_id, NEW.text_version, NEW.language, NEW.text, NEW.ip_address,
             NEW.confirmed_at)
            IS NOT DISTINCT FROM
            (OLD.id, OLD.user_label, OLD.store_id, OLD.text_version, OLD.language, OLD.text, OLD.ip_address,
             OLD.confirmed_at) THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'seller_declarations is append-only' USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER seller_declarations_append_only
    BEFORE UPDATE OR DELETE
    ON seller_declarations
    FOR EACH ROW
EXECUTE FUNCTION jeparla_declarations_append_only();

-- ------------------------------------------------------------------ upload slots

CREATE TABLE document_upload_slots
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Private key the document gets once checked: documents/<store>/<uuid>.<ext>.
    storage_key  TEXT        NOT NULL UNIQUE,
    store_id     BIGINT      NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    product_id   BIGINT REFERENCES products (id) ON DELETE CASCADE,
    check_kind   TEXT        NOT NULL,
    kind         TEXT        NOT NULL,
    file_name    TEXT        NOT NULL,
    content_type TEXT        NOT NULL,
    size_bytes   BIGINT      NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    attached_at  TIMESTAMPTZ,
    discarded_at TIMESTAMPTZ,
    CONSTRAINT document_upload_slots_check_kind CHECK (check_kind IN ('DOCUMENTS', 'EXPERTISE')),
    CONSTRAINT document_upload_slots_expertise_product CHECK ((check_kind = 'EXPERTISE') = (product_id IS NOT NULL)),
    CONSTRAINT document_upload_slots_kind CHECK (
        kind IN ('TAX_ID', 'TRADE_LICENSE', 'ASSAY_CERTIFICATE', 'LAB_REPORT')),
    CONSTRAINT document_upload_slots_content_type CHECK (
        content_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    CONSTRAINT document_upload_slots_size CHECK (size_bytes > 0 AND size_bytes <= 10485760),
    CONSTRAINT document_upload_slots_file_name CHECK (length(file_name) BETWEEN 1 AND 200),
    CONSTRAINT document_upload_slots_expiry CHECK (expires_at > created_at),
    CONSTRAINT document_upload_slots_one_end CHECK (attached_at IS NULL OR discarded_at IS NULL)
);

CREATE INDEX document_upload_slots_open_idx ON document_upload_slots (store_id, expires_at)
    WHERE attached_at IS NULL AND discarded_at IS NULL;
CREATE INDEX document_upload_slots_stale_idx ON document_upload_slots (expires_at)
    WHERE attached_at IS NULL AND discarded_at IS NULL;
CREATE INDEX document_upload_slots_store_idx ON document_upload_slots (store_id, created_at);
CREATE INDEX document_upload_slots_created_idx ON document_upload_slots (created_at);

-- ------------------------------------------------------------------ documents

ALTER TABLE verification_documents
    DROP CONSTRAINT verification_documents_status,
    ADD CONSTRAINT verification_documents_status CHECK (
        status IN ('PENDING', 'VERIFIED', 'REJECTED', 'CHANGES_REQUESTED')),
    -- Reason category of a rejection or a change request (docs/legal/sellers-liability.md, 2c).
    ADD COLUMN reject_reason TEXT,
    ADD CONSTRAINT verification_documents_reject_reason CHECK (reject_reason IS NULL OR reject_reason IN (
        'UNREADABLE', 'EXPIRED', 'MISMATCH', 'WRONG_TYPE', 'HALLMARK_MISSING', 'AUTHENTICITY')),
    -- The declaration the seller confirmed for this upload (#138). Required by the API for every upload.
    ADD COLUMN declaration_id BIGINT REFERENCES seller_declarations (id) ON DELETE RESTRICT;

CREATE INDEX verification_documents_declaration_idx ON verification_documents (declaration_id);

-- ------------------------------------------------------------------ notifications

-- In-app notifications (bell in the header). Title and body are rendered once, in the user's language at the
-- time of the event, so a later change of the message files does not rewrite what the user was told.
CREATE TABLE notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind       TEXT        NOT NULL,
    language   TEXT        NOT NULL,
    title      TEXT        NOT NULL,
    body       TEXT        NOT NULL,
    -- Path in the frontend to act on it, e.g. /merchant/documents.
    link       TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at    TIMESTAMPTZ,
    CONSTRAINT notifications_kind CHECK (length(kind) BETWEEN 1 AND 64),
    CONSTRAINT notifications_language CHECK (language IN ('az', 'en', 'ru')),
    CONSTRAINT notifications_link CHECK (link IS NULL OR link ~ '^/[A-Za-z0-9/_?=&.-]*$')
);

CREATE INDEX notifications_user_idx ON notifications (user_id, created_at DESC, id DESC);
CREATE INDEX notifications_unread_idx ON notifications (user_id) WHERE read_at IS NULL;

-- Emails waiting to be sent (transactional outbox: written in the transaction of the decision, sent after it
-- by EmailOutboxJob). Rows are kept for the record of what was sent.
CREATE TABLE email_outbox
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT REFERENCES notifications (id) ON DELETE SET NULL,
    user_id         BIGINT REFERENCES users (id) ON DELETE CASCADE,
    to_address      TEXT        NOT NULL,
    language        TEXT        NOT NULL,
    subject         TEXT        NOT NULL,
    body            TEXT        NOT NULL,
    status          TEXT        NOT NULL DEFAULT 'PENDING',
    attempts        INTEGER     NOT NULL DEFAULT 0,
    last_error      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at         TIMESTAMPTZ,
    CONSTRAINT email_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT email_outbox_language CHECK (language IN ('az', 'en', 'ru')),
    CONSTRAINT email_outbox_attempts CHECK (attempts >= 0),
    CONSTRAINT email_outbox_sent CHECK ((status = 'SENT') = (sent_at IS NOT NULL))
);

CREATE INDEX email_outbox_pending_idx ON email_outbox (next_attempt_at) WHERE status = 'PENDING';

