-- Occasion collections (#115): "Nişan", "Toy", "Hədiyyə" ... entry pages of the catalog
-- (/collections/{slug}). A seller tags their own products with occasions; the admin renames, reorders
-- and hides the collections. A collection page lists the listed products tagged with it, so the rule
-- is the existing catalog filter (GET /products?collection={slug}) and no new search logic is needed.
--
-- The issue named three tables (collections, collection_products, occasion_tags). The owner decided on
-- 2026-11-18 that the collections ARE the occasions, so one tag list serves both: collections holds the
-- occasions and collection_products the seller's tags.

CREATE TABLE collections
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       TEXT        NOT NULL,
    name_az    TEXT        NOT NULL,
    name_en    TEXT        NOT NULL,
    name_ru    TEXT        NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    -- A hidden collection leaves the public site and the seller form; its tags are kept.
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT collections_slug_key UNIQUE (slug),
    CONSTRAINT collections_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 80),
    CONSTRAINT collections_names_present CHECK (length(btrim(name_az)) > 0 AND length(btrim(name_en)) > 0
        AND length(btrim(name_ru)) > 0 AND length(name_az) <= 80 AND length(name_en) <= 80
        AND length(name_ru) <= 80)
);

COMMENT ON TABLE collections IS 'Occasion collections (#115), admin-managed; hidden ones are active = false';

-- Products are never deleted (soft delete), so the product side cascades only for completeness;
-- removing a collection removes its tags.
CREATE TABLE collection_products
(
    collection_id BIGINT      NOT NULL REFERENCES collections (id) ON DELETE CASCADE,
    product_id    BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (collection_id, product_id)
);

CREATE INDEX collection_products_product_idx ON collection_products (product_id);

COMMENT ON TABLE collection_products IS 'Occasion tags a seller put on a product (#115)';

