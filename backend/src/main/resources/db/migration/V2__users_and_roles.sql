-- Accounts and roles (RBAC: ADMIN, MERCHANT, USER; docs/RBAC.md).

CREATE TABLE users
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            TEXT,
    -- E.164, e.g. +994501234567. Sellers sign up with a phone (PLAN 5.6).
    phone            TEXT,
    password_hash    TEXT        NOT NULL,
    display_name     TEXT        NOT NULL,
    email_verified   BOOLEAN     NOT NULL DEFAULT FALSE,
    phone_verified   BOOLEAN     NOT NULL DEFAULT FALSE,
    preferred_locale TEXT        NOT NULL DEFAULT 'az',
    status           TEXT        NOT NULL DEFAULT 'ACTIVE',
    last_login_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_email_or_phone CHECK (email IS NOT NULL OR phone IS NOT NULL),
    CONSTRAINT users_email_format CHECK (email IS NULL OR (email LIKE '%_@_%' AND length(email) <= 254)),
    CONSTRAINT users_phone_format CHECK (phone IS NULL OR phone ~ '^\+[1-9][0-9]{7,14}$'),
    CONSTRAINT users_display_name_length CHECK (length(btrim(display_name)) BETWEEN 1 AND 120),
    CONSTRAINT users_preferred_locale CHECK (preferred_locale IN ('az', 'en', 'ru')),
    CONSTRAINT users_status CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

-- Emails are unique regardless of case.
CREATE UNIQUE INDEX users_email_key ON users (lower(email));
CREATE UNIQUE INDEX users_phone_key ON users (phone);

CREATE TABLE roles
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    CONSTRAINT roles_name_key UNIQUE (name),
    CONSTRAINT roles_name CHECK (name IN ('ADMIN', 'MERCHANT', 'USER'))
);

INSERT INTO roles (name)
VALUES ('ADMIN'),
       ('MERCHANT'),
       ('USER');

CREATE TABLE user_roles
(
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id    BIGINT      NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX user_roles_role_id_idx ON user_roles (role_id);
