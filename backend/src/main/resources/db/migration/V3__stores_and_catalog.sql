-- Stores, the category tree and finenesses (PLAN 5.2, 5.6, 5.9).

CREATE TABLE stores
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- A merchant cannot be deleted while they own a store: block the store instead.
    owner_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    slug              TEXT        NOT NULL,
    -- Store names are proper names: one value for every language.
    name              TEXT        NOT NULL,
    description_az    TEXT,
    description_en    TEXT,
    description_ru    TEXT,
    city              TEXT        NOT NULL,
    address           TEXT        NOT NULL,
    -- E.164, used for wa.me links.
    whatsapp          TEXT        NOT NULL,
    phone             TEXT,
    social            TEXT,
    -- schema.org openingHours, e.g. "Mo-Fr 10:00-19:00; Sa 11:00-17:00".
    opening_hours     TEXT,
    latitude          NUMERIC(9, 6),
    longitude         NUMERIC(9, 6),
    -- Object key in the public bucket, never a full URL.
    logo_key          TEXT,
    legal_type        TEXT        NOT NULL,
    -- VOEN: 10 digits for companies and sole traders.
    tax_id            TEXT        NOT NULL,
    -- Marketplace status, decided by an admin.
    status            TEXT        NOT NULL DEFAULT 'PENDING',
    -- Reason of the last reject or block, shown to the seller.
    status_note       TEXT,
    -- Jeparla Verified: separate checks (PLAN 5.9). seller = the seller is verified,
    -- documents = business documents checked (PLAN "businessStatus"), identity = ID document.
    seller_status     TEXT        NOT NULL DEFAULT 'NONE',
    documents_status  TEXT        NOT NULL DEFAULT 'NONE',
    identity_status   TEXT        NOT NULL DEFAULT 'NONE',
    approved_at       TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    search_text       TEXT GENERATED ALWAYS AS (jeparla_fold(name || ' ' || city)) STORED,
    CONSTRAINT stores_slug_key UNIQUE (slug),
    CONSTRAINT stores_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 120),
    CONSTRAINT stores_name_length CHECK (length(btrim(name)) BETWEEN 2 AND 80),
    CONSTRAINT stores_whatsapp_format CHECK (whatsapp ~ '^\+[1-9][0-9]{7,14}$'),
    CONSTRAINT stores_phone_format CHECK (phone IS NULL OR phone ~ '^\+[1-9][0-9]{7,14}$'),
    CONSTRAINT stores_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT stores_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT stores_geo_pair CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CONSTRAINT stores_legal_type CHECK (legal_type IN ('COMPANY', 'SOLE_TRADER')),
    CONSTRAINT stores_tax_id_format CHECK (tax_id ~ '^[0-9]{10}$'),
    CONSTRAINT stores_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'BLOCKED')),
    CONSTRAINT stores_seller_status CHECK (seller_status IN ('NONE', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT stores_documents_status CHECK (documents_status IN ('NONE', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT stores_identity_status CHECK (identity_status IN ('NONE', 'PENDING', 'VERIFIED', 'REJECTED'))
);

CREATE INDEX stores_owner_id_idx ON stores (owner_id);
CREATE INDEX stores_status_city_idx ON stores (status, city);
CREATE INDEX stores_search_text_trgm_idx ON stores USING gin (search_text gin_trgm_ops);

-- Category tree (adjacency list). Admin-managed, so all three names are required.
CREATE TABLE categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- A category with children or products cannot be deleted: deactivate it.
    parent_id   BIGINT REFERENCES categories (id) ON DELETE RESTRICT,
    slug        TEXT        NOT NULL,
    name_az     TEXT        NOT NULL,
    name_en     TEXT        NOT NULL,
    name_ru     TEXT        NOT NULL,
    sort_order  INTEGER     NOT NULL DEFAULT 0,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    search_text TEXT GENERATED ALWAYS AS (jeparla_fold(name_az || ' ' || name_en || ' ' || name_ru)) STORED,
    CONSTRAINT categories_slug_key UNIQUE (slug),
    CONSTRAINT categories_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 120),
    CONSTRAINT categories_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT categories_names_not_blank CHECK (
        length(btrim(name_az)) > 0 AND length(btrim(name_en)) > 0 AND length(btrim(name_ru)) > 0)
);

CREATE INDEX categories_parent_id_idx ON categories (parent_id);
CREATE INDEX categories_search_text_trgm_idx ON categories USING gin (search_text gin_trgm_ops);

-- Finenesses are data, not an enum: admins add them (PLAN 4).
CREATE TABLE finenesses
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metal      TEXT        NOT NULL,
    -- Parts per thousand: 375, 585, 750, 916, 999, 925 ...
    value      SMALLINT    NOT NULL,
    label      TEXT        NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT finenesses_metal_value_key UNIQUE (metal, value),
    CONSTRAINT finenesses_metal CHECK (metal IN ('GOLD', 'SILVER', 'PLATINUM', 'PALLADIUM')),
    CONSTRAINT finenesses_value CHECK (value > 0 AND value <= 1000)
);
