package az.jeparla.product;

import az.jeparla.common.i18n.LocalizedText;
import az.jeparla.common.persistence.TimestampedEntity;
import jakarta.persistence.AttributeOverride;
import jakarta.persistence.AttributeOverrides;
import jakarta.persistence.Column;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

/**
 * Node of the category tree (adjacency list, {@code parent_id}). Admin-managed, so all three
 * names are required. A category is deactivated, not deleted.
 */
@Entity
@Table(name = "categories")
public class Category extends TimestampedEntity {

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "parent_id")
    private Category parent;

    @Column(name = "slug", nullable = false, unique = true)
    private String slug;

    @Embedded
    @AttributeOverrides({
            @AttributeOverride(name = "az", column = @Column(name = "name_az", nullable = false)),
            @AttributeOverride(name = "en", column = @Column(name = "name_en", nullable = false)),
            @AttributeOverride(name = "ru", column = @Column(name = "name_ru", nullable = false))
    })
    private LocalizedText name;

    @Column(name = "sort_order", nullable = false)
    private int sortOrder;

    @Column(name = "active", nullable = false)
    private boolean active = true;

    /** Generated by PostgreSQL from the three folded names. */
    @Column(name = "search_text", insertable = false, updatable = false)
    private String searchText;

    protected Category() {
    }

    public Category(Category parent, String slug, LocalizedText name, int sortOrder) {
        this.parent = parent;
        this.slug = slug;
        this.name = name;
        this.sortOrder = sortOrder;
    }

    public Category getParent() {
        return parent;
    }

    public void setParent(Category parent) {
        this.parent = parent;
    }

    public String getSlug() {
        return slug;
    }

    public void setSlug(String slug) {
        this.slug = slug;
    }

    public LocalizedText getName() {
        return name;
    }

    public void setName(LocalizedText name) {
        this.name = name;
    }

    public int getSortOrder() {
        return sortOrder;
    }

    public void setSortOrder(int sortOrder) {
        this.sortOrder = sortOrder;
    }

    public boolean isActive() {
        return active;
    }

    public void setActive(boolean active) {
        this.active = active;
    }

    public String getSearchText() {
        return searchText;
    }
}
