package az.jeparla.product;

import az.jeparla.common.i18n.LocalizedText;
import az.jeparla.common.persistence.TimestampedEntity;
import az.jeparla.store.Store;
import az.jeparla.verification.CheckStatus;
import jakarta.persistence.AttributeOverride;
import jakarta.persistence.AttributeOverrides;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.UUID;
import org.hibernate.annotations.SQLRestriction;

/**
 * A catalog item of one store. Products are never deleted (PLAN 5.2): {@link #softDelete}
 * makes them INACTIVE with {@code deleted_at}; a database trigger rejects DELETE, and the
 * repository has no delete method.
 *
 * <p>Collections are lazy. The public listing loads them in batches
 * ({@code hibernate.default_batch_fetch_size}), so a page costs a fixed number of queries.
 */
@Entity
@Table(name = "products")
public class Product extends TimestampedEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "store_id", nullable = false, updatable = false)
    private Store store;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "category_id", nullable = false)
    private Category category;

    @Column(name = "slug", nullable = false, unique = true)
    private String slug;

    /** The seller writes the Azerbaijani name; en/ru are optional and fall back to az. */
    @Embedded
    @AttributeOverrides({
            @AttributeOverride(name = "az", column = @Column(name = "name_az", nullable = false)),
            @AttributeOverride(name = "en", column = @Column(name = "name_en")),
            @AttributeOverride(name = "ru", column = @Column(name = "name_ru"))
    })
    private LocalizedText name;

    @Embedded
    @AttributeOverrides({
            @AttributeOverride(name = "az", column = @Column(name = "description_az")),
            @AttributeOverride(name = "en", column = @Column(name = "description_en")),
            @AttributeOverride(name = "ru", column = @Column(name = "description_ru"))
    })
    private LocalizedText description;

    /** PRECIOUS or FASHION (#128); fixed at creation (the variants copy it, V13). */
    @Enumerated(EnumType.STRING)
    @Column(name = "material_kind", nullable = false, updatable = false)
    private MaterialKind materialKind = MaterialKind.PRECIOUS;

    /** The precious metal; null for a FASHION product (CHECK {@code products_metal_by_kind}). */
    @Enumerated(EnumType.STRING)
    @Column(name = "metal")
    private Metal metal;

    /** Main material of a FASHION product; null for PRECIOUS. */
    @Enumerated(EnumType.STRING)
    @Column(name = "material")
    private FashionMaterial material;

    /** When the seller confirmed "this is not a precious metal" (FASHION only). */
    @Column(name = "not_precious_confirmed_at")
    private Instant notPreciousConfirmedAt;

    /** The seller hid this APPROVED product; only then may the seller show it again without a review. */
    @Column(name = "hidden_by_seller", nullable = false)
    private boolean hiddenBySeller;

    /** Idempotency-Key of the request that created the product (#39), or null. */
    @Column(name = "idempotency_key", updatable = false)
    private UUID idempotencyKey;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private ProductStatus status = ProductStatus.DRAFT;

    @Column(name = "review_note")
    private String reviewNote;

    /** Physical expertise check of this product (PLAN 5.9). */
    @Enumerated(EnumType.STRING)
    @Column(name = "expertise_status", nullable = false)
    private CheckStatus expertiseStatus = CheckStatus.NONE;

    @Column(name = "submitted_at")
    private Instant submittedAt;

    @Column(name = "published_at")
    private Instant publishedAt;

    @Column(name = "deleted_at")
    private Instant deletedAt;

    /** Generated by PostgreSQL from the folded az/en/ru names. */
    @Column(name = "search_text", insertable = false, updatable = false)
    private String searchText;

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("sortOrder ASC, id ASC")
    private List<ProductImage> images = new ArrayList<>();

    /** Live variants only; removed ones stay in the table for the price history. */
    @OneToMany(mappedBy = "product", cascade = {CascadeType.PERSIST, CascadeType.MERGE})
    @SQLRestriction("deleted_at IS NULL")
    @OrderBy("id ASC")
    private List<ProductVariant> variants = new ArrayList<>();

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("sortOrder ASC, id ASC")
    private List<ProductStone> stones = new ArrayList<>();

    /** Hallmark and label photos (#106), at most one of each kind; not part of the gallery. */
    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("kind ASC")
    private List<ProductEvidencePhoto> evidencePhotos = new ArrayList<>();

    protected Product() {
    }

    public Product(Store store, Category category, String slug, LocalizedText name, Metal metal) {
        this.store = store;
        this.category = category;
        this.slug = slug;
        this.name = name;
        this.metal = Objects.requireNonNull(metal, "metal");
    }

    /**
     * A bijouterie or handmade product (#128): no metal and no fineness, a material, FIXED prices only. The
     * seller confirmed at {@code confirmedAt} that it is not a precious metal.
     */
    public static Product fashion(Store store, Category category, String slug, LocalizedText name,
            FashionMaterial material, Instant confirmedAt) {
        Product product = new Product();
        product.store = store;
        product.category = category;
        product.slug = slug;
        product.name = name;
        product.materialKind = MaterialKind.FASHION;
        product.material = Objects.requireNonNull(material, "material");
        product.notPreciousConfirmedAt = Objects.requireNonNull(confirmedAt, "confirmedAt");
        return product;
    }

    // ------------------------------------------------------------------ lifecycle

    /**
     * Visible in the public catalog. FASHION (bijouterie) products are public too (#128): the public DTOs carry
     * {@code materialKind}, so the catalog shows them in their own section with a clear badge.
     */
    public boolean isPublic() {
        return status == ProductStatus.APPROVED && deletedAt == null;
    }

    public boolean isDeleted() {
        return deletedAt != null;
    }

    public void submitForReview(Instant now) {
        requireNotDeleted();
        this.status = ProductStatus.IN_REVIEW;
        this.submittedAt = now;
        this.hiddenBySeller = false;
    }

    /** Back to a private draft: the seller withdrew it from review, or edited a product hidden earlier. */
    public void backToDraft() {
        requireNotDeleted();
        this.status = ProductStatus.DRAFT;
        this.hiddenBySeller = false;
    }

    /** Publishes the product. The first publication date is kept on re-approval. */
    public void approve(Instant now) {
        requireNotDeleted();
        this.status = ProductStatus.APPROVED;
        this.reviewNote = null;
        this.hiddenBySeller = false;
        if (publishedAt == null) {
            this.publishedAt = now;
        }
    }

    /** The seller hides an APPROVED product (INACTIVE); {@link #showAgain} reverses it without a review. */
    public void hideBySeller() {
        requireNotDeleted();
        if (status != ProductStatus.APPROVED) {
            throw new IllegalStateException("Only an APPROVED product can be hidden, product " + getId() + " is " + status);
        }
        this.status = ProductStatus.INACTIVE;
        this.hiddenBySeller = true;
    }

    /** Shows a product its seller hid, as it was approved. Never a product an admin deactivated. */
    public void showAgain() {
        requireNotDeleted();
        if (status != ProductStatus.INACTIVE || !hiddenBySeller) {
            throw new IllegalStateException("Product " + getId() + " was not hidden by its seller");
        }
        this.status = ProductStatus.APPROVED;
        this.hiddenBySeller = false;
    }

    public void returnToSeller(String note) {
        requireNotDeleted();
        this.status = ProductStatus.RETURNED;
        this.reviewNote = note;
    }

    /** Admin decision: the product is taken down; its seller cannot simply show it again. */
    public void deactivate(String note) {
        this.status = ProductStatus.INACTIVE;
        this.reviewNote = note;
        this.hiddenBySeller = false;
    }

    /** "Deleting" a product: INACTIVE + {@code deleted_at}. Idempotent. */
    public void softDelete(Instant now) {
        this.status = ProductStatus.INACTIVE;
        this.hiddenBySeller = false;
        if (deletedAt == null) {
            this.deletedAt = now;
        }
    }

    private void requireNotDeleted() {
        if (deletedAt != null) {
            throw new IllegalStateException("Product " + getId() + " is deleted");
        }
    }

    // ------------------------------------------------------------------ children

    public void addImage(ProductImage image) {
        image.attachTo(this);
        images.add(image);
    }

    public void removeImage(ProductImage image) {
        images.remove(image);
    }

    /** Adds a hallmark or label photo; remove (and flush) the one of the same kind first. */
    public void addEvidencePhoto(ProductEvidencePhoto photo) {
        if (evidencePhoto(photo.getKind()).isPresent()) {
            throw new IllegalStateException("Product " + getId() + " already has a " + photo.getKind() + " photo");
        }
        photo.attachTo(this);
        evidencePhotos.add(photo);
    }

    public void removeEvidencePhoto(ProductEvidencePhoto photo) {
        evidencePhotos.remove(photo);
    }

    public Optional<ProductEvidencePhoto> evidencePhoto(EvidenceKind kind) {
        return evidencePhotos.stream().filter(photo -> photo.getKind() == kind).findFirst();
    }

    public void addVariant(ProductVariant variant) {
        requireFitting(variant.getFineness(), variant.getPricingMode());
        variant.attachTo(this);
        variants.add(variant);
    }

    /** Variants are soft-deleted: the row stays for the price history and frees its SKU. */
    public void removeVariant(ProductVariant variant, Instant now) {
        variant.markDeleted(now);
        variants.remove(variant);
    }

    public void addStone(ProductStone stone) {
        stone.attachTo(this);
        stones.add(stone);
    }

    public void removeStone(ProductStone stone) {
        stones.remove(stone);
    }

    /** The variant with the lowest price ("priceFrom" of the catalog card). */
    public Optional<ProductVariant> cheapestVariant() {
        return variants.stream()
                .min(Comparator.comparing(ProductVariant::getPrice).thenComparing(ProductVariant::getId,
                        Comparator.nullsLast(Comparator.naturalOrder())));
    }

    public List<ProductImage> getImages() {
        return Collections.unmodifiableList(images);
    }

    public List<ProductVariant> getVariants() {
        return Collections.unmodifiableList(variants);
    }

    public List<ProductStone> getStones() {
        return Collections.unmodifiableList(stones);
    }

    public List<ProductEvidencePhoto> getEvidencePhotos() {
        return Collections.unmodifiableList(evidencePhotos);
    }

    // ------------------------------------------------------------------ accessors

    public Store getStore() {
        return store;
    }

    public Category getCategory() {
        return category;
    }

    public void setCategory(Category category) {
        this.category = category;
    }

    public String getSlug() {
        return slug;
    }

    public void setSlug(String slug) {
        this.slug = slug;
    }

    public LocalizedText getName() {
        return name;
    }

    public void setName(LocalizedText name) {
        this.name = name;
    }

    public LocalizedText getDescription() {
        return description;
    }

    public void setDescription(LocalizedText description) {
        this.description = description;
    }

    public Metal getMetal() {
        return metal;
    }

    /**
     * Changes the metal of a PRECIOUS product. Every live variant must move to a fineness of the new metal in
     * the same transaction: the database checks the pair at commit (V10, deferred foreign key).
     */
    public void setMetal(Metal metal) {
        if (materialKind != MaterialKind.PRECIOUS) {
            throw new IllegalStateException("A FASHION product has no metal: product " + getId());
        }
        this.metal = Objects.requireNonNull(metal, "metal");
    }

    /**
     * A variant's fineness must be of this product's metal (#122; the database enforces it too). The
     * variants of a FASHION product have no fineness and a FIXED price (#128, V13).
     */
    void requireFitting(Fineness fineness, PricingMode pricingMode) {
        if (materialKind == MaterialKind.FASHION) {
            if (fineness != null || pricingMode != PricingMode.FIXED) {
                throw new IllegalArgumentException("A FASHION product has no fineness and FIXED prices only");
            }
            return;
        }
        if (fineness == null) {
            throw new IllegalArgumentException("A variant of a PRECIOUS product needs a fineness");
        }
        if (fineness.getMetal() != metal) {
            throw new IllegalArgumentException(
                    "Fineness " + fineness.getLabel() + " is " + fineness.getMetal() + ", the product is " + metal);
        }
    }

    public MaterialKind getMaterialKind() {
        return materialKind;
    }

    public FashionMaterial getMaterial() {
        return material;
    }

    /** The material of a FASHION product. */
    public void setMaterial(FashionMaterial material) {
        if (materialKind != MaterialKind.FASHION) {
            throw new IllegalStateException("Only a FASHION product has a material: product " + getId());
        }
        this.material = Objects.requireNonNull(material, "material");
    }

    public Instant getNotPreciousConfirmedAt() {
        return notPreciousConfirmedAt;
    }

    public boolean isHiddenBySeller() {
        return hiddenBySeller;
    }

    public UUID getIdempotencyKey() {
        return idempotencyKey;
    }

    public void setIdempotencyKey(UUID idempotencyKey) {
        this.idempotencyKey = idempotencyKey;
    }

    public ProductStatus getStatus() {
        return status;
    }

    public String getReviewNote() {
        return reviewNote;
    }

    public CheckStatus getExpertiseStatus() {
        return expertiseStatus;
    }

    /** Refused for a FASHION product (#128): there is nothing to certify, so it never shows that badge. */
    public void setExpertiseStatus(CheckStatus expertiseStatus) {
        if (materialKind == MaterialKind.FASHION && expertiseStatus != CheckStatus.NONE) {
            throw new IllegalStateException("A FASHION product has no expertise check: product " + getId());
        }
        this.expertiseStatus = expertiseStatus;
    }

    public Instant getSubmittedAt() {
        return submittedAt;
    }

    public Instant getPublishedAt() {
        return publishedAt;
    }

    public Instant getDeletedAt() {
        return deletedAt;
    }

    public String getSearchText() {
        return searchText;
    }
}
