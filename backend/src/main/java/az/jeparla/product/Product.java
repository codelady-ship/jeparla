package az.jeparla.product;

import az.jeparla.common.i18n.LocalizedText;
import az.jeparla.common.persistence.TimestampedEntity;
import az.jeparla.store.Store;
import az.jeparla.verification.CheckStatus;
import jakarta.persistence.AttributeOverride;
import jakarta.persistence.AttributeOverrides;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import org.hibernate.annotations.SQLRestriction;

/**
 * A catalog item of one store. Products are never deleted (PLAN 5.2): {@link #softDelete}
 * makes them INACTIVE with {@code deleted_at}; a database trigger rejects DELETE, and the
 * repository has no delete method.
 *
 * <p>Collections are lazy. The public listing loads them in batches
 * ({@code hibernate.default_batch_fetch_size}), so a page costs a fixed number of queries.
 */
@Entity
@Table(name = "products")
public class Product extends TimestampedEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "store_id", nullable = false, updatable = false)
    private Store store;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "category_id", nullable = false)
    private Category category;

    @Column(name = "slug", nullable = false, unique = true)
    private String slug;

    /** The seller writes the Azerbaijani name; en/ru are optional and fall back to az. */
    @Embedded
    @AttributeOverrides({
            @AttributeOverride(name = "az", column = @Column(name = "name_az", nullable = false)),
            @AttributeOverride(name = "en", column = @Column(name = "name_en")),
            @AttributeOverride(name = "ru", column = @Column(name = "name_ru"))
    })
    private LocalizedText name;

    @Embedded
    @AttributeOverrides({
            @AttributeOverride(name = "az", column = @Column(name = "description_az")),
            @AttributeOverride(name = "en", column = @Column(name = "description_en")),
            @AttributeOverride(name = "ru", column = @Column(name = "description_ru"))
    })
    private LocalizedText description;

    @Enumerated(EnumType.STRING)
    @Column(name = "metal", nullable = false)
    private Metal metal;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private ProductStatus status = ProductStatus.DRAFT;

    @Column(name = "review_note")
    private String reviewNote;

    /** Physical expertise check of this product (PLAN 5.9). */
    @Enumerated(EnumType.STRING)
    @Column(name = "expertise_status", nullable = false)
    private CheckStatus expertiseStatus = CheckStatus.NONE;

    @Column(name = "submitted_at")
    private Instant submittedAt;

    @Column(name = "published_at")
    private Instant publishedAt;

    @Column(name = "deleted_at")
    private Instant deletedAt;

    /** Generated by PostgreSQL from the folded az/en/ru names. */
    @Column(name = "search_text", insertable = false, updatable = false)
    private String searchText;

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("sortOrder ASC, id ASC")
    private List<ProductImage> images = new ArrayList<>();

    /** Live variants only; removed ones stay in the table for the price history. */
    @OneToMany(mappedBy = "product", cascade = {CascadeType.PERSIST, CascadeType.MERGE})
    @SQLRestriction("deleted_at IS NULL")
    @OrderBy("id ASC")
    private List<ProductVariant> variants = new ArrayList<>();

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("sortOrder ASC, id ASC")
    private List<ProductStone> stones = new ArrayList<>();

    protected Product() {
    }

    public Product(Store store, Category category, String slug, LocalizedText name, Metal metal) {
        this.store = store;
        this.category = category;
        this.slug = slug;
        this.name = name;
        this.metal = metal;
    }

    // ------------------------------------------------------------------ lifecycle

    /** Visible in the public catalog. */
    public boolean isPublic() {
        return status == ProductStatus.APPROVED && deletedAt == null;
    }

    public boolean isDeleted() {
        return deletedAt != null;
    }

    public void submitForReview(Instant now) {
        requireNotDeleted();
        this.status = ProductStatus.IN_REVIEW;
        this.submittedAt = now;
    }

    /** Publishes the product. The first publication date is kept on re-approval. */
    public void approve(Instant now) {
        requireNotDeleted();
        this.status = ProductStatus.APPROVED;
        this.reviewNote = null;
        if (publishedAt == null) {
            this.publishedAt = now;
        }
    }

    public void returnToSeller(String note) {
        requireNotDeleted();
        this.status = ProductStatus.RETURNED;
        this.reviewNote = note;
    }

    public void deactivate(String note) {
        this.status = ProductStatus.INACTIVE;
        this.reviewNote = note;
    }

    /** "Deleting" a product: INACTIVE + {@code deleted_at}. Idempotent. */
    public void softDelete(Instant now) {
        this.status = ProductStatus.INACTIVE;
        if (deletedAt == null) {
            this.deletedAt = now;
        }
    }

    private void requireNotDeleted() {
        if (deletedAt != null) {
            throw new IllegalStateException("Product " + getId() + " is deleted");
        }
    }

    // ------------------------------------------------------------------ children

    public void addImage(ProductImage image) {
        image.attachTo(this);
        images.add(image);
    }

    public void removeImage(ProductImage image) {
        images.remove(image);
    }

    public void addVariant(ProductVariant variant) {
        requireMetalOf(variant.getFineness());
        variant.attachTo(this);
        variants.add(variant);
    }

    /** Variants are soft-deleted: the row stays for the price history and frees its SKU. */
    public void removeVariant(ProductVariant variant, Instant now) {
        variant.markDeleted(now);
        variants.remove(variant);
    }

    public void addStone(ProductStone stone) {
        stone.attachTo(this);
        stones.add(stone);
    }

    public void removeStone(ProductStone stone) {
        stones.remove(stone);
    }

    /** The variant with the lowest price ("priceFrom" of the catalog card). */
    public Optional<ProductVariant> cheapestVariant() {
        return variants.stream()
                .min(Comparator.comparing(ProductVariant::getPrice).thenComparing(ProductVariant::getId,
                        Comparator.nullsLast(Comparator.naturalOrder())));
    }

    public List<ProductImage> getImages() {
        return Collections.unmodifiableList(images);
    }

    public List<ProductVariant> getVariants() {
        return Collections.unmodifiableList(variants);
    }

    public List<ProductStone> getStones() {
        return Collections.unmodifiableList(stones);
    }

    // ------------------------------------------------------------------ accessors

    public Store getStore() {
        return store;
    }

    public Category getCategory() {
        return category;
    }

    public void setCategory(Category category) {
        this.category = category;
    }

    public String getSlug() {
        return slug;
    }

    public void setSlug(String slug) {
        this.slug = slug;
    }

    public LocalizedText getName() {
        return name;
    }

    public void setName(LocalizedText name) {
        this.name = name;
    }

    public LocalizedText getDescription() {
        return description;
    }

    public void setDescription(LocalizedText description) {
        this.description = description;
    }

    public Metal getMetal() {
        return metal;
    }

    /**
     * Changes the metal. Every live variant must move to a fineness of the new metal in the same
     * transaction: the database checks the pair at commit (V10, deferred foreign key).
     */
    public void setMetal(Metal metal) {
        this.metal = metal;
    }

    /** A variant's fineness must be of this product's metal (#122; the database enforces it too). */
    void requireMetalOf(Fineness fineness) {
        if (fineness.getMetal() != metal) {
            throw new IllegalArgumentException(
                    "Fineness " + fineness.getLabel() + " is " + fineness.getMetal() + ", the product is " + metal);
        }
    }

    public ProductStatus getStatus() {
        return status;
    }

    public String getReviewNote() {
        return reviewNote;
    }

    public CheckStatus getExpertiseStatus() {
        return expertiseStatus;
    }

    public void setExpertiseStatus(CheckStatus expertiseStatus) {
        this.expertiseStatus = expertiseStatus;
    }

    public Instant getSubmittedAt() {
        return submittedAt;
    }

    public Instant getPublishedAt() {
        return publishedAt;
    }

    public Instant getDeletedAt() {
        return deletedAt;
    }

    public String getSearchText() {
        return searchText;
    }
}
