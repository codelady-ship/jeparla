// Generates src/app/tokens.css from docs/design/tokens.json (the single source of truth).
// Usage: npm run tokens          write the file
//        npm run tokens -- --check  exit 1 if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = resolve(here, "../../docs/design/tokens.json");
export const TOKENS_CSS = resolve(here, "../src/app/tokens.css");

// shadcn/ui variable -> Jeparla role
const SHADCN = {
  background: "bg",
  foreground: "text",
  card: "surface",
  "card-foreground": "text",
  popover: "surface",
  "popover-foreground": "text",
  primary: "primary",
  "primary-foreground": "on-primary",
  secondary: "surface-muted",
  "secondary-foreground": "text",
  muted: "surface-muted",
  "muted-foreground": "text-muted",
  accent: "surface-muted",
  "accent-foreground": "text",
  destructive: "danger",
  border: "border",
  input: "input",
  ring: "ring",
  "chart-1": "primary",
  "chart-2": "accent",
  "chart-3": "success",
  "chart-4": "warning",
  "chart-5": "danger",
  sidebar: "surface",
  "sidebar-foreground": "text",
  "sidebar-primary": "primary",
  "sidebar-primary-foreground": "on-primary",
  "sidebar-accent": "surface-muted",
  "sidebar-accent-foreground": "text",
  "sidebar-border": "border",
  "sidebar-ring": "ring",
};

// Brand roles shadcn has no name for
const BRAND = {
  surface: "surface",
  gold: "accent",
  "on-gold": "on-accent",
  "gold-text": "accent-text",
  "on-destructive": "on-danger",
  success: "success",
  warning: "warning",
};

function block(selector, palette, extra = "") {
  const lines = [];
  for (const [name, role] of Object.entries({ ...SHADCN, ...BRAND })) {
    if (!(role in palette)) throw new Error(`tokens.json: missing role "${role}"`);
    lines.push(`  --${name}: ${palette[role].toLowerCase()};`);
  }
  return `${selector} {\n${extra}${lines.join("\n")}\n}\n`;
}

export function buildCss(tokens) {
  const { light, dark } = tokens.color;
  return [
    "/* Generated by scripts/tokens.mjs from docs/design/tokens.json. Do not edit by hand. */\n",
    block(":root", light, `  color-scheme: light;\n  --radius: ${tokens.radius};\n`),
    block(".dark", dark, "  color-scheme: dark;\n"),
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = buildCss(JSON.parse(readFileSync(TOKENS_JSON, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(TOKENS_CSS, "utf8") !== css) {
      console.error("tokens.css is out of date. Run: npm run tokens");
      process.exit(1);
    }
  } else {
    writeFileSync(TOKENS_CSS, css);
    console.log("wrote", TOKENS_CSS);
  }
}
