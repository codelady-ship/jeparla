// Generates src/app/tokens.css and src/lib/brand-colors.json from docs/design/tokens.json
// (the single source of truth). The JSON serves places that cannot read CSS variables:
// the web app manifest, the theme-color meta tag and the offline page.
// Usage: npm run tokens          write the files
//        npm run tokens -- --check  exit 1 if a file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = resolve(here, "../../docs/design/tokens.json");
export const TOKENS_CSS = resolve(here, "../src/app/tokens.css");
export const BRAND_COLORS_JSON = resolve(here, "../src/lib/brand-colors.json");

// shadcn/ui variable -> Jeparla role
const SHADCN = {
  background: "bg",
  foreground: "text",
  card: "surface",
  "card-foreground": "text",
  popover: "surface",
  "popover-foreground": "text",
  primary: "primary",
  "primary-foreground": "on-primary",
  secondary: "surface-muted",
  "secondary-foreground": "text",
  muted: "surface-muted",
  "muted-foreground": "text-muted",
  accent: "surface-muted",
  "accent-foreground": "text",
  destructive: "danger",
  border: "border",
  input: "input",
  ring: "ring",
  "chart-1": "primary",
  "chart-2": "accent",
  "chart-3": "success",
  "chart-4": "warning",
  "chart-5": "danger",
  sidebar: "surface",
  "sidebar-foreground": "text",
  "sidebar-primary": "primary",
  "sidebar-primary-foreground": "on-primary",
  "sidebar-accent": "surface-muted",
  "sidebar-accent-foreground": "text",
  "sidebar-border": "border",
  "sidebar-ring": "ring",
};

// Brand roles shadcn has no name for
const BRAND = {
  surface: "surface",
  // Warm beige of the utility bar above the header (owner reference, 2026-11-22).
  "surface-warm": "surface-warm",
  gold: "accent",
  "on-gold": "on-accent",
  "gold-text": "accent-text",
  "on-destructive": "on-danger",
  success: "success",
  warning: "warning",
};

function block(selector, palette, extra = "") {
  const lines = [];
  for (const [name, role] of Object.entries({ ...SHADCN, ...BRAND })) {
    if (!(role in palette)) throw new Error(`tokens.json: missing role "${role}"`);
    lines.push(`  --${name}: ${palette[role].toLowerCase()};`);
  }
  return `${selector} {\n${extra}${lines.join("\n")}\n}\n`;
}

function motionVars(motion) {
  const lines = [];
  for (const [k, v] of Object.entries(motion.duration)) lines.push(`  --duration-${k}: ${v};`);
  for (const [k, v] of Object.entries(motion.easing)) lines.push(`  --ease-${k}: ${v};`);
  lines.push(`  --reveal-distance: ${motion["reveal-distance"]};`);
  lines.push(`  --reveal-shift: ${motion["reveal-shift"]};`);
  lines.push(`  --reveal-stagger: ${motion["reveal-stagger"]};`);
  return lines.join("\n") + "\n";
}

/** Hero scene colors: fixed, the same in both themes (--scene-ink, --scene-gold ...). */
function sceneVars(scene = {}) {
  return Object.entries(scene)
    .filter(([k]) => !k.startsWith("$"))
    .map(([k, v]) => `  --scene-${k}: ${v.toLowerCase()};`)
    .join("\n");
}

export function buildCss(tokens) {
  const { light, dark, scene } = tokens.color;
  return [
    "/* Generated by scripts/tokens.mjs from docs/design/tokens.json. Do not edit by hand. */\n",
    block(
      ":root",
      light,
      `  color-scheme: light;\n  --radius: ${tokens.radius};\n${motionVars(tokens.motion)}${sceneVars(scene)}\n`,
    ),
    block(".dark", dark, "  color-scheme: dark;\n"),
  ].join("\n");
}

/** Light, dark and scene palettes as JSON, without the `$description` notes. */
export function buildBrandColors(tokens) {
  const strip = (palette) =>
    Object.fromEntries(Object.entries(palette).filter(([k]) => !k.startsWith("$")));
  const { light, dark, scene } = tokens.color;
  const colors = { light: strip(light), dark: strip(dark), scene: strip(scene) };
  return JSON.stringify(colors, null, 2) + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(TOKENS_JSON, "utf8"));
  const outputs = [
    [TOKENS_CSS, buildCss(tokens)],
    [BRAND_COLORS_JSON, buildBrandColors(tokens)],
  ];
  if (process.argv.includes("--check")) {
    for (const [file, content] of outputs) {
      let current = "";
      try {
        current = readFileSync(file, "utf8");
      } catch {}
      if (current !== content) {
        console.error(`${file} is out of date. Run: npm run tokens`);
        process.exit(1);
      }
    }
  } else {
    for (const [file, content] of outputs) {
      writeFileSync(file, content);
      console.log("wrote", file);
    }
  }
}
