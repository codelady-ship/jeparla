/**
 * AI model library (#130) as the admin manages it: every model, inactive too, with
 * its reference photos, audience, skin tone, style and origin. The admin adds a
 * model, uploads its reference photos per pose, orders the library, picks the
 * default of an audience and deactivates a model (never deletes it). Models are
 * AI-made (not real people) and uploaded by the admin, never generated by the site.
 * The backend checks the ADMIN role on every call.
 */
export function AiModelList({ models: initial }: { models: AiModel[] }) {
  const t = useTranslations("Admin.aiModels");
  const [models, setModels] = useState(initial);
  const [editing, setEditing] = useState<AiModel | "new" | null>(null);
  const [photoFor, setPhotoFor] = useState<AiModel | null>(null);
  const [toggling, setToggling] = useState<AiModel | null>(null);
  const update = (changed: AiModel) => setModels((all) => upsertModel(all, changed));
  const nextOrder = models.reduce((max, m) => Math.max(max, m.sortOrder), 0) + 10;

  return (
    <div className="flex flex-col gap-6">
      <ul className="flex list-disc flex-col gap-1 pl-5 text-sm text-muted-foreground">
        <li>{t("rules.notReal")}</li>
        <li>{t("rules.uploaded")}</li>
        <li>{t("rules.deactivate")}</li>
        <li>{t("rules.credits")}</li>
      </ul>
      <Button type="button" size="lg" className="self-start" onClick={() => setEditing("new")}>
        <Plus aria-hidden />
        {t("add")}
      </Button>
      {models.length === 0 ? (
        <div className="flex flex-col items-center gap-3 rounded-lg border border-dashed p-8 text-center">
          <UserRound aria-hidden className="size-8 text-gold-text" />
          <p className="font-semibold">{t("empty.title")}</p>
          <p className="max-w-prose text-sm text-muted-foreground">{t("empty.text")}</p>
        </div>
      ) : (
        <ul className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {models.map((model) => (
            <ModelCard
              key={model.id}
              model={model}
              onEdit={() => setEditing(model)}
              onPhoto={() => setPhotoFor(model)}
              onToggle={() => setToggling(model)}
              onChange={update}
            />
          ))}
        </ul>
      )}
      {editing !== null && (
        <ModelDialog
          model={editing === "new" ? null : editing}
          nextOrder={nextOrder}
          onClose={() => setEditing(null)}
          onSaved={update}
        />
      )}
      {photoFor !== null && (
        <PhotoDialog model={photoFor} onClose={() => setPhotoFor(null)} onSaved={update} />
      )}
      {toggling !== null && (
        <ToggleDialog model={toggling} onClose={() => setToggling(null)} onSaved={update} />
      )}
    </div>
  );
}

function ModelCard({
  model,
  onEdit,
  onPhoto,
  onToggle,
  onChange,
}: {
  model: AiModel;
  onEdit: () => void;
  onPhoto: () => void;
  onToggle: () => void;
  onChange: (m: AiModel) => void;
}) {
  const t = useTranslations("Admin.aiModels");
  const [busy, setBusy] = useState<string | null>(null);

  async function call(key: string, method: string, endpoint: string, done: string) {
    setBusy(key);
    const result = await sendJson<AiModel>(method, endpoint, {});
    setBusy(null);
    if (!result.ok) {
      notices.show(failure(result.errors.form, t("failed")));
      return;
    }
    onChange(result.data);
    notices.show(done);
  }

  const cover = model.images[0];
  return (
    <li className="flex flex-col gap-3 rounded-lg border p-4">
      <div className="relative aspect-[4/5] overflow-hidden rounded-md bg-muted">
        {cover && (
          <Image
            src={cover.url}
            alt={t("photoAlt", { name: model.name })}
            fill
            sizes="(min-width: 1024px) 33vw, (min-width: 640px) 50vw, 100vw"
            className="object-cover"
            unoptimized
          />
        )}
      </div>
      <div className="flex flex-wrap items-center gap-2">
        <span className="font-semibold">{model.name}</span>
        {model.isDefault && (
          <Badge variant="gold">
            <Star aria-hidden />
            {t("default")}
          </Badge>
        )}
        <Badge variant={model.active ? "default" : "outline"}>
          {model.active ? t("active") : t("inactive")}
        </Badge>
      </div>
      <dl className="grid grid-cols-2 gap-x-3 gap-y-1 text-sm">
        <dt className="text-muted-foreground">{t("audienceLabel")}</dt>
        <dd>{t(`audience.${model.audience}`)}</dd>
        <dt className="text-muted-foreground">{t("skinToneLabel")}</dt>
        <dd>{t(`skinTone.${model.skinTone}`)}</dd>
        <dt className="text-muted-foreground">{t("styleLabel")}</dt>
        <dd>{t(`style.${model.style}`)}</dd>
        <dt className="text-muted-foreground">{t("sortLabel")}</dt>
        <dd className="tabular-nums">{model.sortOrder}</dd>
        <dt className="text-muted-foreground">{t("posesLabel")}</dt>
        <dd>
          {model.poses.length === 0
            ? t("noPhotos")
            : model.poses.map((p) => t(`pose.${p}`)).join(", ")}
        </dd>
      </dl>
      <p className="text-xs break-words text-muted-foreground">
        {t("origin", { origin: model.origin })}
      </p>
      {model.images.length > 0 && (
        <ul className="grid grid-cols-4 gap-2" aria-label={t("photosLabel", { name: model.name })}>
          {model.images.map((img) => (
            <li key={img.id} className="flex flex-col gap-1">
              <span className="relative aspect-[4/5] overflow-hidden rounded-md bg-muted">
                <Image
                  src={img.url}
                  alt={t("posePhotoAlt", { name: model.name, pose: t(`pose.${img.pose}`) })}
                  fill
                  sizes="80px"
                  className="object-cover"
                  unoptimized
                />
              </span>
              <span className="truncate text-xs text-muted-foreground">
                {t(`pose.${img.pose}`)}
              </span>
              <Button
                type="button"
                variant="ghost"
                size="icon"
                disabled={busy !== null}
                aria-label={t("removePhoto", { pose: t(`pose.${img.pose}`), name: model.name })}
                onClick={() =>
                  void call(
                    `photo:${img.id}`,
                    "DELETE",
                    `/api/admin/ai-models/${model.id}/images/${img.id}`,
                    t("photoRemoved"),
                  )
                }
              >
                <X aria-hidden />
              </Button>
            </li>
          ))}
        </ul>
      )}
      <div className="mt-auto flex flex-wrap gap-2">
        <Button type="button" variant="outline" size="lg" onClick={onEdit}>
          <Pencil aria-hidden />
          {t("edit")}
        </Button>
        <Button type="button" variant="outline" size="lg" onClick={onPhoto}>
          <ImagePlus aria-hidden />
          {t("addPhoto")}
        </Button>
        {model.active && !model.isDefault && (
          <Button
            type="button"
            variant="outline"
            size="lg"
            disabled={busy !== null}
            aria-busy={busy === "default" || undefined}
            onClick={() =>
              void call(
                "default",
                "POST",
                `/api/admin/ai-models/${model.id}/default`,
                t("madeDefault", { name: model.name }),
              )
            }
          >
            <Star aria-hidden />
            {t("makeDefault")}
          </Button>
        )}
        <Button type="button" variant="outline" size="lg" onClick={onToggle}>
          {model.active ? <EyeOff aria-hidden /> : <Eye aria-hidden />}
          {model.active ? t("deactivate") : t("activate")}
        </Button>
      </div>
    </li>
  );
}

/** The backend's own sentence (already in the admin's language) or the generic failure. */
function failure(form: string | undefined, generic: string): string {
  return form && isMessage(form) ? form : generic;
}

function ModelDialog({
  model,
  nextOrder,
  onClose,
  onSaved,
}: {
  model: AiModel | null;
  nextOrder: number;
  onClose: () => void;
  onSaved: (m: AiModel) => void;
}) {
  const t = useTranslations("Admin.aiModels");
  const form = useAdminForm();
  const [input, setInput] = useState<AiModelInput>(
    model ? modelInput(model) : emptyModelInput(nextOrder),
  );
  const set = <K extends keyof AiModelInput>(key: K, value: AiModelInput[K]) =>
    setInput((v) => ({ ...v, [key]: value }));

  async function save() {
    const saved = await form.submit<AiModel, typeof aiModelSchema>(
      model ? "PUT" : "POST",
      model ? `/api/admin/ai-models/${model.id}` : "/api/admin/ai-models",
      aiModelSchema,
      input,
    );
    if (!saved) return;
    onSaved(saved);
    onClose();
    notices.show(t(model ? "saved" : "added", { name: saved.name }));
  }

  return (
    <AdminDialog
      open
      onOpenChange={(o) => !o && onClose()}
      title={model ? t("editTitle", { name: model.name }) : t("add")}
      description={t("formText")}
      submitLabel={t("save")}
      busy={form.busy}
      formError={form.errors.form}
      onSubmit={() => void save()}
    >
      <Field label={t("nameLabel")} error={form.errors.name} hint={t("nameHint")}>
        {(props) => (
          <input
            {...props}
            value={input.name}
            maxLength={60}
            onChange={(e) => set("name", e.target.value)}
            className={fieldClass}
          />
        )}
      </Field>
      <Field label={t("audienceLabel")} error={form.errors.audience} hint={t("audienceHint")}>
        {(props) => (
          <select
            {...props}
            value={input.audience}
            onChange={(e) => set("audience", e.target.value as AiModelInput["audience"])}
            className={fieldClass}
          >
            {MODEL_AUDIENCES.map((a) => (
              <option key={a} value={a}>
                {t(`audience.${a}`)}
              </option>
            ))}
          </select>
        )}
      </Field>
      <Field label={t("skinToneLabel")} error={form.errors.skinTone}>
        {(props) => (
          <select
            {...props}
            value={input.skinTone}
            onChange={(e) => set("skinTone", e.target.value as AiModelInput["skinTone"])}
            className={fieldClass}
          >
            {SKIN_TONES.map((s) => (
              <option key={s} value={s}>
                {t(`skinTone.${s}`)}
              </option>
            ))}
          </select>
        )}
      </Field>
      <Field label={t("styleLabel")} error={form.errors.style}>
        {(props) => (
          <select
            {...props}
            value={input.style}
            onChange={(e) => set("style", e.target.value as AiModelInput["style"])}
            className={fieldClass}
          >
            {MODEL_STYLES.map((s) => (
              <option key={s} value={s}>
                {t(`style.${s}`)}
              </option>
            ))}
          </select>
        )}
      </Field>
      <Field label={t("originLabel")} error={form.errors.origin} hint={t("originHint")}>
        {(props) => (
          <input
            {...props}
            value={input.origin}
            maxLength={300}
            onChange={(e) => set("origin", e.target.value)}
            className={fieldClass}
          />
        )}
      </Field>
      <Field label={t("sortLabel")} error={form.errors.sortOrder} hint={t("sortHint")}>
        {(props) => (
          <input
            {...props}
            type="number"
            inputMode="numeric"
            min={0}
            max={10000}
            value={Number.isNaN(input.sortOrder) ? "" : input.sortOrder}
            onChange={(e) => set("sortOrder", e.target.valueAsNumber)}
            className={fieldClass}
          />
        )}
      </Field>
    </AdminDialog>
  );
}

/** Deactivate (leaves new jobs, approved images stay) or bring a model back. */
function ToggleDialog({
  model,
  onClose,
  onSaved,
}: {
  model: AiModel;
  onClose: () => void;
  onSaved: (m: AiModel) => void;
}) {
  const t = useTranslations("Admin.aiModels");
  const form = useAdminForm();
  const active = !model.active;

  async function save() {
    const saved = await form.submit<AiModel, typeof aiModelSchema>(
      "PUT",
      `/api/admin/ai-models/${model.id}`,
      aiModelSchema,
      { ...modelInput(model), active },
    );
    if (!saved) return;
    onSaved(saved);
    onClose();
    notices.show(t(active ? "activated" : "deactivated", { name: saved.name }));
  }

  return (
    <AdminDialog
      open
      onOpenChange={(o) => !o && onClose()}
      title={t(active ? "activateTitle" : "deactivateTitle", { name: model.name })}
      description={t(active ? "activateText" : "deactivateText")}
      submitLabel={active ? t("activate") : t("deactivate")}
      destructive={!active}
      busy={form.busy}
      formError={form.errors.form}
      onSubmit={() => void save()}
    />
  );
}

/**
 * One reference photo with its pose: presigned upload straight to storage, then
 * attach (the backend checks the stored file's size, magic number and dimensions).
 */
function PhotoDialog({
  model,
  onClose,
  onSaved,
}: {
  model: AiModel;
  onClose: () => void;
  onSaved: (m: AiModel) => void;
}) {
  const t = useTranslations("Admin.aiModels");
  const missing = MODEL_POSES.filter((p) => !model.poses.includes(p));
  const [pose, setPose] = useState<ModelPose>(missing[0] ?? "HAND");
  const [file, setFile] = useState<File | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | undefined>();

  async function upload() {
    if (!file) {
      setError(t("photoErrors.required"));
      return;
    }
    const problem = photoProblem(file);
    if (problem) {
      setError(t(`photoErrors.${problem}`));
      return;
    }
    setBusy(true);
    setError(undefined);
    const slot = await sendJson<{
      key: string;
      url: string;
      method: string;
      headers: Record<string, string>;
    }>("POST", `/api/admin/ai-models/${model.id}/images/uploads`, {
      contentType: file.type,
      sizeBytes: file.size,
    });
    if (!slot.ok) {
      setBusy(false);
      setError(failure(slot.errors.form, t("failed")));
      return;
    }
    const put = await fetch(slot.data.url, {
      method: slot.data.method || "PUT",
      headers: slot.data.headers,
      body: file,
    }).catch(() => null);
    if (!put?.ok) {
      setBusy(false);
      setError(t("photoErrors.upload"));
      return;
    }
    const body = modelAttachSchema.parse({ key: slot.data.key, pose });
    const saved = await sendJson<AiModel>("POST", `/api/admin/ai-models/${model.id}/images`, body);
    setBusy(false);
    if (!saved.ok) {
      setError(failure(saved.errors.form, t("failed")));
      return;
    }
    onSaved(saved.data);
    onClose();
    notices.show(t("photoAdded", { name: model.name }));
  }

  return (
    <AdminDialog
      open
      onOpenChange={(o) => !busy && !o && onClose()}
      title={t("photoTitle", { name: model.name })}
      description={t("photoText")}
      submitLabel={t("upload")}
      busy={busy}
      onSubmit={() => void upload()}
    >
      <Field label={t("poseLabel")}>
        {(props) => (
          <select
            {...props}
            value={pose}
            onChange={(e) => setPose(z.enum(MODEL_POSES).parse(e.target.value))}
            className={fieldClass}
          >
            {MODEL_POSES.map((p) => (
              <option key={p} value={p}>
                {t(`pose.${p}`)}
              </option>
            ))}
          </select>
        )}
      </Field>
      <Field label={t("fileLabel")} error={error} hint={t("fileHint")}>
        {(props) => (
          <input
            {...props}
            type="file"
            accept={MODEL_IMAGE_TYPES.join(",")}
            onChange={(e) => {
              setFile(e.target.files?.[0] ?? null);
              setError(undefined);
            }}
            className="text-sm file:mr-3 file:h-11 file:rounded-lg file:border file:border-input file:bg-background file:px-3 file:text-sm"
          />
        )}
      </Field>
    </AdminDialog>
  );
}
